// Vocabulary master index — hierarchical per-folder + one-file cache (Aaron, 2026-06-09):
// canonical homes are the TYPE folders (words/, letters/, shapes/, colors/, temperatures/);
// grams/ is the generated measure-view (indexed separately). Each canonical folder gets an
// INDEX.md (its entries + child folders' indexes, composed); vocab/MASTER-INDEX.md is the
// single-file MASTER cache (one read = the whole vocabulary). Deterministic; --check gates.
//   bun vocab/gen/MasterIndex.ts            (rewrite indexes)
//   bun vocab/gen/MasterIndex.ts --check     (verify; exit 1 if stale)
import { readdirSync, lstatSync, existsSync, readFileSync } from "node:fs";
import { readFileBounded, writeTextIfChanged } from "../../src/Core.TypeScript/io/safe-io.ts";
import { join, basename, relative } from "node:path";


/**
 * 0o644 — the mode `writeFileSync` produced under the repo's umask, kept
 * exactly. `writeTextIfChanged` defaults to 0o600, and a generated repository
 * file that only its generator can read is a change nobody asked for.
 */
const GENERATED_FILE_MODE = 0o644;

/** One generated index. 32 MiB is far above the master index on `main`. */
const INDEX_MAX_BYTES = 32 * 1024 * 1024;

const VOCAB = new URL("../", import.meta.url).pathname;
const CANON = ["words", "letters", "shapes", "colors", "temperatures", "personas"]; // type homes (real)
const ROOT_INDEX = join(VOCAB, "MASTER-INDEX.md");

const carved = (f: string): string[] =>
  readFileSync(f, "utf8").split("\n").filter((l) => l.startsWith("> ")).map((l) => l.slice(2).trim());

type Entry = { term: string; rel: string; senses: string[] };
type Folder = { dir: string; entries: Entry[]; children: Folder[] };

function build(dir: string): Folder {
  const f: Folder = { dir, entries: [], children: [] };
  for (const n of readdirSync(dir).sort()) {
    if (n === "README.md" || n === "INDEX.md") continue;
    const p = join(dir, n); const st = lstatSync(p);
    if (st.isSymbolicLink()) continue;
    if (st.isDirectory()) f.children.push(build(p));
    else if (n.endsWith(".md")) f.entries.push({ term: basename(n, ".md"), rel: relative(VOCAB, p), senses: carved(p) });
  }
  return f;
}
const flatten = (f: Folder): Entry[] => [...f.entries, ...f.children.flatMap(flatten)];
const lines = (e: Entry): string =>
  e.senses.length <= 1
    ? `- **${e.term}** — ${e.senses[0] ?? ""} \`(${e.rel})\`\n`
    : `- **${e.term}** \`(${e.rel})\` — ${e.senses.length} senses (discriminator required):\n` + e.senses.map((s, i) => `  ${i + 1}. ${s}\n`).join("");

const writes: { path: string; body: string }[] = [];
// markdownlint MD012: collapse any run of 3+ newlines to a single blank line.
const norm = (s: string): string => s.replace(/\n{3,}/g, "\n\n");
function folderIndex(f: Folder) {
  let md = `# ${relative(VOCAB, f.dir)}/INDEX — regenerated (do not edit)\n\n`;
  for (const e of [...f.entries].sort((a, b) => a.term.localeCompare(b.term))) md += lines(e);
  for (const c of [...f.children].sort((a, b) => a.dir.localeCompare(b.dir))) {
    md += `\n## ${relative(VOCAB, c.dir)}/\n\n`;
    for (const e of flatten(c).sort((a, b) => a.term.localeCompare(b.term))) md += lines(e);
  }
  writes.push({ path: join(f.dir, "INDEX.md"), body: norm(md) });
  for (const c of f.children) folderIndex(c);
}

const forest = CANON.map((r) => join(VOCAB, r)).filter(existsSync).map(build);
for (const f of forest) folderIndex(f);

const all = forest.flatMap(flatten).sort((a, b) => a.rel.localeCompare(b.rel));
let root = `# VOCAB-INDEX — MASTER single-file cache of every traveler (GENERATED, one-file read)\n\n`;
root += `> Do NOT edit by hand. Regenerated by vocab/gen/MasterIndex.ts from the canonical TYPE\n`;
root += `> homes (words/letters/shapes/colors/temperatures). grams/ is the generated measure-view.\n`;
root += `> The DST test framework loads THIS as the master index (one read). ${all.length} travelers.\n\n`;
let last = "";
for (const e of all) { const r = e.rel.split("/")[0] ?? ""; if (r !== last) { root += `\n## ${r}\n\n`; last = r; } root += lines(e); }
writes.push({ path: ROOT_INDEX, body: norm(root) });

const check = process.argv.includes("--check");
let stale = 0;
for (const w of writes) {
  if (check) {
    // --check READS ONLY. `readFileBounded` opens once; `not-found` is the only
    // error that means "absent", so a present-but-unreadable index is reported
    // as stale-and-unreadable rather than silently compared against "".
    const read = readFileBounded(w.path, { maxBytes: INDEX_MAX_BYTES });
    if (!read.ok && read.error.kind !== "not-found") {
      stale++;
      console.error(`UNREADABLE: ${relative(VOCAB, w.path)}: ${read.error.message}`);
      continue;
    }
    const cur = read.ok ? read.value.text : "";
    if (cur !== w.body) { stale++; console.error(`STALE: ${relative(VOCAB, w.path)}`); }
    continue;
  }
  // ONE DESCRIPTOR EACH WAY. `existsSync(p) ? readFileSync(p) : ""` followed by
  // `writeFileSync(p)` resolved one name three times and made the write
  // conditional on the first resolution -- CodeQL `js/file-system-race`.
  const written = writeTextIfChanged(w.path, w.body, { mode: GENERATED_FILE_MODE, maxBytes: INDEX_MAX_BYTES });
  if (!written.ok) { console.error(`vocab-index: cannot write ${relative(VOCAB, w.path)}: ${written.error.message}`); process.exit(1); }
}
if (check) {
  if (stale) { console.error(`vocab-index: ${stale} stale — run: bun vocab/gen/MasterIndex.ts`); process.exit(1); }
  console.log(`vocab-index: ${writes.length} indexes up to date (${all.length} travelers).`);
} else console.log(`vocab-index: wrote ${writes.length} indexes (${all.length} travelers); master = vocab/MASTER-INDEX.md.`);
