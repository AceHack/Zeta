// Vocabulary master index — hierarchical per-folder + one-file cache (Aaron, 2026-06-09):
// canonical homes are the TYPE folders (words/, letters/, shapes/, colors/, temperatures/);
// grams/ is the generated measure-view (indexed separately). Each canonical folder gets an
// INDEX.md (its entries + child folders' indexes, composed); vocab/MASTER-INDEX.md is the
// single-file MASTER cache (one read = the whole vocabulary). Deterministic; --check gates.
//   bun vocab/gen/MasterIndex.ts            (rewrite indexes)
//   bun vocab/gen/MasterIndex.ts --check     (verify; exit 1 if stale)
import { readdirSync, lstatSync, existsSync, readFileSync, writeFileSync } from "node:fs";
import { join, basename, relative } from "node:path";
const VOCAB = new URL("../", import.meta.url).pathname;
const CANON = ["words", "letters", "shapes", "colors", "temperatures", "personas"]; // type homes (real)
const ROOT_INDEX = join(VOCAB, "MASTER-INDEX.md");
const carved = (f) => readFileSync(f, "utf8").split("\n").filter((l) => l.startsWith("> ")).map((l) => l.slice(2).trim());
function build(dir) {
    const f = { dir, entries: [], children: [] };
    for (const n of readdirSync(dir).sort()) {
        if (n === "README.md" || n === "INDEX.md")
            continue;
        const p = join(dir, n);
        const st = lstatSync(p);
        if (st.isSymbolicLink())
            continue;
        if (st.isDirectory())
            f.children.push(build(p));
        else if (n.endsWith(".md"))
            f.entries.push({ term: basename(n, ".md"), rel: relative(VOCAB, p), senses: carved(p) });
    }
    return f;
}
const flatten = (f) => [...f.entries, ...f.children.flatMap(flatten)];
const lines = (e) => e.senses.length <= 1
    ? `- **${e.term}** — ${e.senses[0] ?? ""} \`(${e.rel})\`\n`
    : `- **${e.term}** \`(${e.rel})\` — ${e.senses.length} senses (discriminator required):\n` + e.senses.map((s, i) => `  ${i + 1}. ${s}\n`).join("");
const writes = [];
// markdownlint MD012: collapse any run of 3+ newlines to a single blank line.
const norm = (s) => s.replace(/\n{3,}/g, "\n\n");
function folderIndex(f) {
    let md = `# ${relative(VOCAB, f.dir)}/INDEX — regenerated (do not edit)\n\n`;
    for (const e of [...f.entries].sort((a, b) => a.term.localeCompare(b.term)))
        md += lines(e);
    for (const c of [...f.children].sort((a, b) => a.dir.localeCompare(b.dir))) {
        md += `\n## ${relative(VOCAB, c.dir)}/\n\n`;
        for (const e of flatten(c).sort((a, b) => a.term.localeCompare(b.term)))
            md += lines(e);
    }
    writes.push({ path: join(f.dir, "INDEX.md"), body: norm(md) });
    for (const c of f.children)
        folderIndex(c);
}
const forest = CANON.map((r) => join(VOCAB, r)).filter(existsSync).map(build);
for (const f of forest)
    folderIndex(f);
const all = forest.flatMap(flatten).sort((a, b) => a.rel.localeCompare(b.rel));
let root = `# VOCAB-INDEX — MASTER single-file cache of every traveler (GENERATED, one-file read)\n\n`;
root += `> Do NOT edit by hand. Regenerated by vocab/gen/MasterIndex.ts from the canonical TYPE\n`;
root += `> homes (words/letters/shapes/colors/temperatures). grams/ is the generated measure-view.\n`;
root += `> The DST test framework loads THIS as the master index (one read). ${all.length} travelers.\n\n`;
let last = "";
for (const e of all) {
    const r = e.rel.split("/")[0] ?? "";
    if (r !== last) {
        root += `\n## ${r}\n\n`;
        last = r;
    }
    root += lines(e);
}
writes.push({ path: ROOT_INDEX, body: norm(root) });
const check = process.argv.includes("--check");
let stale = 0;
for (const w of writes) {
    const cur = existsSync(w.path) ? readFileSync(w.path, "utf8") : "";
    if (check) {
        if (cur !== w.body) {
            stale++;
            console.error(`STALE: ${relative(VOCAB, w.path)}`);
        }
    }
    else
        writeFileSync(w.path, w.body);
}
if (check) {
    if (stale) {
        console.error(`vocab-index: ${stale} stale — run: bun vocab/gen/MasterIndex.ts`);
        process.exit(1);
    }
    console.log(`vocab-index: ${writes.length} indexes up to date (${all.length} travelers).`);
}
else
    console.log(`vocab-index: wrote ${writes.length} indexes (${all.length} travelers); master = vocab/MASTER-INDEX.md.`);
