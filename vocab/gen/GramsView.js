// grams/ is the MEASURE/DIMENSION view, NOT a canonical home (Aaron, 2026-06-09:
// "grams is not the canonical home, it's the symlink — grams is the measure, the
// dimension"). Canonical homes are the TYPE folders (words/, letters/, shapes/,
// colors/, temperatures/ — real files). This regenerates grams/<n>/<term>.md as
// symlinks into the canonical homes, sliced by the n-gram measure (token count).
// Generated + checked in; --check gates staleness.
//   bun vocab/gen/GramsView.ts          (regenerate grams/ symlink view)
//   bun vocab/gen/GramsView.ts --check   (verify; exit 1 if stale/dangling)
import { readdirSync, lstatSync, existsSync, mkdirSync, rmSync, symlinkSync, readlinkSync, writeFileSync } from "node:fs";
import { join, basename, relative } from "node:path";
const VOCAB = new URL("../", import.meta.url).pathname;
const CANON = ["words", "letters", "shapes", "colors", "temperatures", "personas"]; // the type homes (real)
const GRAMS = join(VOCAB, "grams");
function walkReal(dir) {
    const out = [];
    if (!existsSync(dir))
        return out;
    for (const n of readdirSync(dir).sort()) {
        if (n === "README.md" || n === "INDEX.md")
            continue;
        const p = join(dir, n);
        const st = lstatSync(p);
        if (st.isSymbolicLink())
            continue;
        if (st.isDirectory())
            out.push(...walkReal(p));
        else if (n.endsWith(".md"))
            out.push(p);
    }
    return out;
}
const ngram = (term) => term.split(/[-\s]+/).filter(Boolean).length; // the measure
// desired grams view: Map<"grams/<n>/<name>.md", canonicalRelPath>
const want = new Map();
const seenLC = new Set(); // case-INSENSITIVE collision guard (macOS/Windows FS)
for (const home of CANON)
    for (const f of walkReal(join(VOCAB, home))) {
        const term = basename(f, ".md");
        const n = ngram(term);
        let name = `${term}.md`;
        let key = join(GRAMS, String(n), name);
        if (seenLC.has(key.toLowerCase())) {
            name = `${home}-${term}.md`;
            key = join(GRAMS, String(n), name);
        } // discriminate collisions by type
        seenLC.add(key.toLowerCase());
        want.set(key, relative(join(GRAMS, String(n)), f)); // relative symlink target
    }
const check = process.argv.includes("--check");
if (check) {
    let bad = 0;
    for (const [link, target] of want) {
        if (!existsSync(link)) {
            console.error(`MISSING grams symlink: ${relative(VOCAB, link)}`);
            bad++;
            continue;
        }
        if (!lstatSync(link).isSymbolicLink() || readlinkSync(link) !== target) {
            console.error(`WRONG grams symlink: ${relative(VOCAB, link)}`);
            bad++;
        }
        if (!existsSync(link)) {
            console.error(`DANGLING: ${relative(VOCAB, link)}`);
            bad++;
        }
    }
    // also flag extras
    if (existsSync(GRAMS))
        for (const n of readdirSync(GRAMS)) {
            const nd = join(GRAMS, n);
            if (!lstatSync(nd).isDirectory())
                continue;
            for (const f of readdirSync(nd)) {
                if (f === "README.md")
                    continue;
                if (!want.has(join(nd, f))) {
                    console.error(`EXTRA grams symlink: grams/${n}/${f}`);
                    bad++;
                }
            }
        }
    if (bad) {
        console.error(`grams-view: ${bad} issue(s) — run: bun vocab/gen/GramsView.ts`);
        process.exit(1);
    }
    console.log(`grams-view: up to date (${want.size} symlinks).`);
}
else {
    rmSync(GRAMS, { recursive: true, force: true });
    for (const [link, target] of want) {
        mkdirSync(join(link, ".."), { recursive: true });
        symlinkSync(target, link);
    }
    // a README at the grams root
    writeFileSync(join(GRAMS, "README.md"), `# grams/ — the MEASURE/DIMENSION view (generated symlinks; NOT a canonical home)\n\n` +
        `grams is the n-gram **measure** (token count), the dimension we slice the vocabulary by.\n` +
        `\`grams/<n>/<term>.md\` is a **symlink** into the term's canonical TYPE home (words/letters/\n` +
        `shapes/colors/temperatures). Generated by vocab/gen/GramsView.ts; do not edit by hand.\n`);
    console.log(`grams-view: wrote ${want.size} symlinks across grams/<n>/.`);
}
