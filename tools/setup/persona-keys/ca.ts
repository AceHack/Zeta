// Zeta pre-cluster SSH Certificate Authority + cert signing — the forward-compatible
// "Option B" slice of the unified key-onboarding flow (workitem
// 081KVM1TK3Z08QG0R0002959G6 §"Trust distribution" + §"Pre-cluster bootstrap"). It
// SHIPS THE MECHANISM ONLY; it generates NO real CA and commits NO real CA key.
//
// THE TRUST MODEL (why a CA at all):
//   Today every node carries a LIST of trusted pubkeys
//   (full-ai-cluster/nixos/modules/operator-ssh-keys.nix → authorizedKeys.keys) — the
//   N×M trap: every node must list every dev machine. The SSH-CA replaces that list:
//   nodes trust ONE CA pubkey (`TrustedUserCAKeys`); each dev machine's device key is
//   SIGNED into a cert carrying `principal=<user>` + machine id + a validity window
//   (the rolling-keys discipline). N-trust-1, not N×M; revocation is per-machine.
//   git is the DISTRIBUTION channel for the CA *public* key — never the secret store.
//   Migration (no model change): this git-distributed CA pubkey → Vault custody +
//   cert-manager issuance/rotation later (same shape).
//
// SECURITY INVARIANTS (security-class slice — honesty over green):
//  1. The CA PRIVATE key + any seed NEVER touch argv / stdout / git. The CA keypair is
//     generated by the injected `CaEffects.genCa` door, which writes the private key to a
//     local file under umask 077 (the runner's job) and returns ONLY the PUBLIC key text.
//     Private bytes never cross this module's boundary, are never printed, never returned.
//  2. Only the CA PUBLIC key and CERTS (certs are public) are publishable. `ensureCa`
//     writes ONLY the public key to maintainers/<ca>/ssh-ca.pub; `signMachineCert` writes
//     ONLY a `-cert.pub` (a public certificate). This module commits NOTHING.
//  3. `--dry-run` generates NOTHING and writes NOTHING — returns "would-*".
//  4. CA-keypair GENERATION is OPERATOR-RUN. This PR ships the mechanism; the operator runs
//     `ca` later to produce the real CA + the real ssh-ca.pub. No real CA key is committed.
//
// Noninterference (manifesto §13): the host environment (filesystem, ssh-keygen runner)
// enters ONLY through the injected `CaEffects` — so the dry-run + the temp-dir tests are
// deterministic and never touch a real CA, real keys, or the network.
//
// Anchors (Beacon): OpenSSH certificate authorities — `ssh-keygen(1)` `-s`/`-I`/`-n`/`-V`,
// `sshd(8)` `TrustedUserCAKeys`, OpenSSH `PROTOCOL.certkeys`. ed25519 keys — Bernstein et
// al. (Ed25519, 2011). The "one CA, N machines" model = SSH host/user-CA prior art
// (Facebook/Netflix BLESS-style short-lived SSH certs). Vault SSH secrets engine + Jetstack
// cert-manager = the in-cluster migration target (same trust model, upgraded custody).
import { spawnSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { join } from "node:path";
// SHARED biometric-approval gate — the agent EXECUTES keygen/sign; the operator's Touch ID /
// Windows Hello is the AUTHORIZATION (Aaron 2026-06-21). Both sensitive ops (generate CA key,
// sign a cert with the CA private key) are gated FAIL-CLOSED behind a biometric confirm.
import { requireBiometric, type BiometricAuth, type BiometricResult } from "./biometric.ts";
export type { BiometricAuth, BiometricResult } from "./biometric.ts";

/** The host-environment doors — the ONLY channel for ambient influence (noninterference).
 *  Every door is PUBLIC-safe by construction: `genCa`/`signCert` return only public text,
 *  the private/CA key is written to a local file by the runner and never read back here. */
export interface CaEffects {
  /** True iff a path exists (presence checks — never reads the contents of a secret). */
  readonly exists: (path: string) => boolean;
  /** Read a PUBLIC text artifact (a pubkey / a cert). Never used on a private path. */
  readonly readText: (path: string) => string;
  /** Write a PUBLIC text artifact (the CA public key, or a public certificate). */
  readonly writeText: (path: string, content: string) => void;
  /** Create a directory (recursive). */
  readonly mkdirp: (path: string) => void;
  /**
   * Generate an SSH CA ed25519 keypair at `caKeyPath` (private) + `caKeyPath.pub` (public).
   * The runner writes the PRIVATE key under umask 077; this door returns ONLY the PUBLIC key
   * text — the private bytes NEVER cross this boundary.
   */
  readonly genCa: (caKeyPath: string, comment: string) => string;
  /**
   * Sign `req.devicePubPath` (a per-machine device PUBLIC key) into a certificate using the
   * CA private key at `req.caKeyPath`. Writes ONLY the public `<devicePubPath base>-cert.pub`
   * and returns its text (a cert is public). The CA private key is consumed by the runner
   * (ssh-keygen -s); it is never read into this process and never returned.
   */
  readonly signCert: (req: SignCertRequest) => SignCertOutput;
}

/** A cert-signing request — all PUBLIC inputs (a device PUBLIC key + cert metadata) plus the
 *  LOCAL path to the CA private key (consumed by the runner, never read across the boundary). */
export interface SignCertRequest {
  /** Local path to the CA PRIVATE key (consumed by ssh-keygen -s; never read here). */
  readonly caKeyPath: string;
  /** Path to the per-machine device PUBLIC key to be signed. */
  readonly devicePubPath: string;
  /** Certificate identity (`-I`) — a human-readable label (e.g. "<user>@<host>"). */
  readonly certId: string;
  /** Principal(s) the cert authorizes (`-n`) — the USER the cert binds to (e.g. "aaron"). */
  readonly principal: string;
  /** Validity window (`-V`), OpenSSH form (e.g. "+52w"); the rolling-keys discipline. */
  readonly validity: string;
}

/** The result of a sign — the written cert path + its (public) text. No private material. */
export interface SignCertOutput {
  /** Path the `-cert.pub` was written to (next to the device pubkey). */
  readonly certPath: string;
  /** The certificate text (public — safe to print / publish / commit). */
  readonly certText: string;
}

/** Default validity window for a signed device cert — the rolling-keys discipline
 *  (a cert expires; you re-sign). 52 weeks is a conservative pre-cluster default. */
export const DEFAULT_CERT_VALIDITY = "+52w";

/** Where the CA PRIVATE key lives locally (operator-held; NEVER published, NEVER committed). */
export function caPrivateKeyPath(home: string = homedir()): string {
  return join(home, ".config", "zeta", "ca", "ssh_ca_ed25519");
}

/** Where the CA PUBLIC key is committed for git-distribution → fed to `TrustedUserCAKeys`.
 *  This path is REFERENCED by ssh-ca.nix; it LANDS only when the operator runs `ca`. */
export function caPublicKeyPath(repoRoot: string, ca: string): string {
  return join(repoRoot, "maintainers", ca, "ssh-ca.pub");
}

/** Where a signed device certificate is written — next to the device pubkey it certifies. */
export function certPath(devicePubPath: string): string {
  // ssh-keygen -s names the cert "<base>-cert.pub" where base is the pubkey minus ".pub".
  const base = devicePubPath.endsWith(".pub") ? devicePubPath.slice(0, -4) : devicePubPath;
  return base + "-cert.pub";
}

/** What a `ca` (generate-CA) run did (or, with dryRun, WOULD do). No private material here. */
export interface CaResult {
  readonly dryRun: boolean;
  /** "generated" | "exists" (idempotent: an existing CA is a no-op) | "would-generate"
   *  | "aborted-biometric" (the operator did NOT approve → fail-closed, NOTHING generated). */
  readonly action: "generated" | "exists" | "would-generate" | "aborted-biometric";
  /** Local path the CA PRIVATE key lives at (never its contents). */
  readonly caPrivatePath: string;
  /** Repo path the CA PUBLIC key would/did get written to (when `commitPub`). */
  readonly caPublicPath: string;
  /** The CA PUBLIC key text, when present/generated (safe to print). Undefined on dry-run. */
  readonly caPublicKey?: string;
  /** True iff we wrote the CA public key to the repo path (never true on dry-run). */
  readonly committedPub: boolean;
  /** The biometric approval outcome (present only when the gate was invoked — i.e. a real
   *  keygen was attempted; absent on dry-run, on the idempotent `exists` no-op, and never
   *  carries a secret). */
  readonly biometric?: BiometricResult;
}

/**
 * Generate (or, idempotently, recognise) the SSH CA keypair — AGENT-RUN, OPERATOR-APPROVED.
 * The agent EXECUTES the keygen; a biometric confirm (Touch ID / Windows Hello) is the
 * operator's AUTHORIZATION. Generates ONLY a CA keypair via the injected `genCa` door (private
 * written locally under umask 077 by the runner; only the PUBLIC key returned). With
 * `commitPub`, writes ONLY the CA PUBLIC key to maintainers/<ca>/ssh-ca.pub (no git commit).
 *
 * BIOMETRIC GATE + FAIL-CLOSED: when a real keygen is about to happen (the CA does NOT already
 * exist and it is not a dry-run), `biometricAuth()` MUST return ok:true first. On ok:false the
 * run aborts ("aborted-biometric") and `genCa` is NEVER invoked — NO CA key is created. The
 * idempotent `exists` no-op (no private material created) and `--dry-run` (creates nothing) do
 * NOT prompt.
 *
 * @param biometricAuth the SHARED approval gate (biometric.ts). Tests inject a fake; the CLI
 *                      injects `realBiometric()`. Required only for the real-keygen path.
 * @param commitPub when true, write the CA PUBLIC key to the repo path (the operator then
 *                  commits it; the CA public key is the git-distributed trust root).
 * @param dryRun    when true, NOTHING is generated, written, or prompted — "would-generate".
 */
export async function ensureCa(
  fx: CaEffects,
  opts: {
    /** The CA identity (the maintainers/<ca>/ subdir; e.g. the operator persona). */
    readonly ca: string;
    readonly repoRoot: string;
    readonly home?: string;
    readonly commitPub?: boolean;
    readonly dryRun?: boolean;
    /** SHARED biometric approval door — required for the real keygen path (fail-closed). */
    readonly biometricAuth?: BiometricAuth;
  },
): Promise<CaResult> {
  const caPrivatePath = opts.home === undefined ? caPrivateKeyPath() : caPrivateKeyPath(opts.home);
  const caPublicPath = caPublicKeyPath(opts.repoRoot, opts.ca);
  const dryRun = opts.dryRun === true;
  const wantCommit = opts.commitPub === true;
  const alreadyExists = fx.exists(caPrivatePath);

  if (dryRun) {
    return {
      dryRun: true,
      action: alreadyExists ? "exists" : "would-generate",
      caPrivatePath,
      caPublicPath,
      committedPub: false,
    };
  }

  let caPublicKey: string;
  let action: CaResult["action"];
  let biometric: BiometricResult | undefined;
  if (alreadyExists) {
    // Idempotent: an existing CA is a no-op (no private material created → no gate). Read
    // back its PUBLIC half only.
    caPublicKey = fx.readText(caPrivatePath + ".pub").trim();
    action = "exists";
  } else {
    // BIOMETRIC GATE — fail-closed. A real keygen creates private material; require approval.
    biometric = await requireBiometric(
      opts.biometricAuth,
      `Approve: generate SSH CA keypair for ${opts.ca}`,
    );
    if (!biometric.ok) {
      return {
        dryRun: false,
        action: "aborted-biometric",
        caPrivatePath,
        caPublicPath,
        committedPub: false,
        biometric,
      };
    }
    caPublicKey = fx.genCa(caPrivatePath, `${opts.ca} (zeta-ssh-ca)`).trim();
    action = "generated";
  }

  const bio = biometric !== undefined ? { biometric } : {};
  if (wantCommit) {
    fx.mkdirp(dirOf(caPublicPath));
    fx.writeText(caPublicPath, caPublicKey.endsWith("\n") ? caPublicKey : caPublicKey + "\n");
    return { dryRun: false, action, caPrivatePath, caPublicPath, caPublicKey, committedPub: true, ...bio };
  }

  return { dryRun: false, action, caPrivatePath, caPublicPath, caPublicKey, committedPub: false, ...bio };
}

/** What a `cert` (sign-device-key) run did (or, with dryRun, WOULD do). Public only. */
export interface CertResult {
  readonly dryRun: boolean;
  /** "signed" | "would-sign" | "no-ca" (CA private absent) | "no-device-key" (pubkey absent)
   *  | "aborted-biometric" (operator did NOT approve → fail-closed, NOTHING signed). */
  readonly action: "signed" | "would-sign" | "no-ca" | "no-device-key" | "aborted-biometric";
  readonly caPrivatePath: string;
  readonly devicePubPath: string;
  readonly certPath: string;
  readonly certId: string;
  readonly principal: string;
  readonly validity: string;
  /** The certificate text, when signed (public — safe to print). Undefined otherwise. */
  readonly certText?: string;
  /** The biometric approval outcome (present only when the gate was invoked — i.e. a real
   *  sign was attempted; absent on dry-run + clean skips; never carries a secret). */
  readonly biometric?: BiometricResult;
}

/**
 * Sign a per-machine device PUBLIC key into a certificate (`principal=<user>` + machine id +
 * a validity window) via the injected `signCert` door (ssh-keygen -s under the hood) — AGENT-RUN,
 * OPERATOR-APPROVED. The agent EXECUTES the sign; a biometric confirm is the operator's
 * AUTHORIZATION (signing CONSUMES the CA private key, so it must be approved). The CA private
 * key is consumed by the runner; it is never read into this process.
 *
 * Reads the machine's PUBLIC key from `devicePubPath` (the machine.ts registry seam —
 * `machines/<host>.pub`, the USER-INDEPENDENT machine registry). This cert is the ONLY place
 * the (user × machine) pair is named: a PURE machine key (host-only) signed with
 * `principal=<user>` (pure-key model, Aaron 2026-06-21). Fail-closed: a missing CA or device
 * key returns a typed `no-ca` / `no-device-key` (no partial work) and NEVER prompts.
 * `--dry-run` signs NOTHING and never prompts.
 *
 * BIOMETRIC GATE + FAIL-CLOSED: when a real sign is about to happen (CA + device key present,
 * not dry-run), `biometricAuth()` MUST return ok:true first. On ok:false the run aborts
 * ("aborted-biometric") and `signCert` is NEVER invoked — NO cert is produced.
 *
 * @param biometricAuth the SHARED approval gate (biometric.ts). Required for the real-sign path.
 */
export async function signMachineCert(
  fx: CaEffects,
  opts: {
    /** The USER the cert binds to (the `-n` principal — trust anchored at the user). */
    readonly user: string;
    /** A machine id for the cert identity (`-I`), e.g. the sanitized hostname. */
    readonly machineId: string;
    /** Path to the per-machine device PUBLIC key to sign (the registry `machines/<host>.pub`). */
    readonly devicePubPath: string;
    readonly home?: string;
    /** Validity window (OpenSSH `-V` form). Defaults to DEFAULT_CERT_VALIDITY. */
    readonly validity?: string;
    readonly dryRun?: boolean;
    /** SHARED biometric approval door — required for the real sign path (fail-closed). */
    readonly biometricAuth?: BiometricAuth;
  },
): Promise<CertResult> {
  const caPrivatePath = opts.home === undefined ? caPrivateKeyPath() : caPrivateKeyPath(opts.home);
  const validity = opts.validity ?? DEFAULT_CERT_VALIDITY;
  // Key ID names the certified SUBJECT = the machine key, so it is the machine id ALONE — NOT
  // `user@machine`. A composite user×machine Key ID is the N×M smell (Aaron, 2026-06-21; same
  // shape as the #8926 hybrid-key error): it would mint a distinct cert per (user, machine) pair
  // → O(N×M) certs. The user binding lives in the PRINCIPAL (`-n`, below), so one cert per machine
  // (Key ID = machine, principals = authorized user(s)) keeps it O(N+M). Multi-user on a shared
  // box = re-sign the one machine cert with more principals (still one cert per machine).
  const certId = opts.machineId;
  const outPath = certPath(opts.devicePubPath);
  const dryRun = opts.dryRun === true;

  const base = {
    caPrivatePath,
    devicePubPath: opts.devicePubPath,
    certPath: outPath,
    certId,
    principal: opts.user,
    validity,
  };

  // Fail-closed presence checks (BEFORE any work, BEFORE any prompt) — a missing CA or device
  // key is a typed no-op, never a partial sign. (Checked even on dry-run so the plan is honest.)
  if (!fx.exists(caPrivatePath)) {
    return { ...base, dryRun, action: "no-ca" };
  }
  if (!fx.exists(opts.devicePubPath)) {
    return { ...base, dryRun, action: "no-device-key" };
  }

  if (dryRun) {
    return { ...base, dryRun: true, action: "would-sign" };
  }

  // BIOMETRIC GATE — fail-closed. A real sign consumes the CA private key; require approval.
  const biometric = await requireBiometric(
    opts.biometricAuth,
    `Approve: sign cert for machine ${opts.machineId} (principal=${opts.user})`,
  );
  if (!biometric.ok) {
    return { ...base, dryRun: false, action: "aborted-biometric", biometric };
  }

  const out = fx.signCert({
    caKeyPath: caPrivatePath,
    devicePubPath: opts.devicePubPath,
    certId,
    principal: opts.user,
    validity,
  });
  return { ...base, dryRun: false, action: "signed", certText: out.certText, biometric };
}

function dirOf(p: string): string {
  const i = p.lastIndexOf("/");
  return i >= 0 ? p.slice(0, i) : ".";
}

/** The REAL host effects (used by the CLI). ssh-keygen generates the CA in-process; the CA
 *  PRIVATE key file is created under umask 077 by ssh-keygen and is never read by us. */
export function realEffects(): CaEffects {
  return {
    exists: (p) => existsSync(p),
    readText: (p) => readFileSync(p, "utf8"),
    writeText: (p, c) => writeFileSync(p, c, { mode: 0o644 }),
    mkdirp: (p) => mkdirSync(p, { recursive: true }),
    genCa: (caKeyPath, comment) => {
      mkdirSync(dirOf(caKeyPath), { recursive: true, mode: 0o700 });
      const prevUmask = process.umask(0o077); // CA private key must not be group/other readable
      try {
        // ssh-keygen generates the CA key itself — no secret on argv. -N "" = no passphrase
        // (the operator may add one); the private file stays LOCAL under umask 077.
        const r = spawnSync(
          "ssh-keygen",
          ["-t", "ed25519", "-f", caKeyPath, "-N", "", "-C", comment],
          { encoding: "utf8", stdio: ["ignore", "pipe", "pipe"] },
        );
        if (r.status !== 0) {
          throw new Error(`ssh-keygen (CA) failed (status ${r.status ?? "signal"}): ${r.stderr ?? ""}`);
        }
      } finally {
        process.umask(prevUmask);
      }
      // Read back ONLY the public half.
      return readFileSync(caKeyPath + ".pub", "utf8");
    },
    signCert: (req) => {
      // ssh-keygen -s <ca> -I <id> -n <principal> -V <validity> <devicePub>
      // Writes "<devicePub base>-cert.pub" (public). The CA private key is read by ssh-keygen,
      // never by us; the cert is public output.
      const r = spawnSync(
        "ssh-keygen",
        [
          "-s",
          req.caKeyPath,
          "-I",
          req.certId,
          "-n",
          req.principal,
          "-V",
          req.validity,
          req.devicePubPath,
        ],
        { encoding: "utf8", stdio: ["ignore", "pipe", "pipe"] },
      );
      if (r.status !== 0) {
        throw new Error(`ssh-keygen -s (sign) failed (status ${r.status ?? "signal"}): ${r.stderr ?? ""}`);
      }
      const out = certPath(req.devicePubPath);
      return { certPath: out, certText: readFileSync(out, "utf8") };
    },
  };
}
