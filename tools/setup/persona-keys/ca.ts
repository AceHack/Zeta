/** The host-environment doors — the ONLY channel for ambient influence (noninterference).
 *  Every door is PUBLIC-safe by construction: `genCa`/`signCert` return only public text,
 *  the private/CA key is written to a local file by the runner and never read back here. */
export interface CaEffects extends CeremonyBriefEffects {
  /** True iff a path exists (presence checks — never reads the contents of a secret). */
  readonly exists: (path: string) => boolean;
  /** Read a PUBLIC text artifact (a pubkey / a cert). Never used on a private path. */
  readonly readText: (path: string) => string;
  /** Write a PUBLIC text artifact (the CA public key, or a public certificate). */
  readonly writeText: (path: string, content: string) => void;
  /** Create a directory (recursive). */
  readonly mkdirp: (path: string) => void;
  /**
   * Generate an SSH CA ed25519 keypair at `caKeyPath` (private) + `caKeyPath.pub` (public).
   * The runner writes the PRIVATE key under umask 077; this door returns ONLY the PUBLIC key
   * text — the private bytes NEVER cross this boundary.
   */
  readonly genCa: (caKeyPath: string, comment: string) => string;
  /**
   * Sign `req.devicePubPath` (a per-machine device PUBLIC key) into a certificate using the
   * CA private key at `req.caKeyPath`. Writes ONLY the public `<devicePubPath base>-cert.pub`
   * and returns its text (a cert is public). The CA private key is consumed by the runner
   * (ssh-keygen -s); it is never read into this process and never returned.
   */
  readonly signCert: (req: SignCertRequest) => SignCertOutput;
}

/** A cert-signing request — all PUBLIC inputs (a device PUBLIC key + cert metadata) plus the
 *  LOCAL path to the CA private key (consumed by the runner, never read across the boundary). */
export interface SignCertRequest {
  /** Local path to the CA PRIVATE key (consumed by ssh-keygen -s; never read here). */
  readonly caKeyPath: string;
  /** Path to the per-machine device PUBLIC key to be signed. */
  readonly devicePubPath: string;
  /** Certificate identity (`-I`) — a MACHINE-ONLY label (the host id; #8969 made the Key ID
   *  machine-only — NEVER a `user@machine` composite, the #8926 N×M lesson). */
  readonly certId: string;
  /** The principals (`-n`) the cert authorizes — the USER LIST it binds to (e.g.
   *  `["aaron", "addison"]` for a co-owned machine). A single-owner cert is a one-element list.
   *  The (user × machine) pairing lives HERE, in the list — never in a composite key/id. */
  readonly principals: readonly string[];
  /** Validity window (`-V`), OpenSSH form (e.g. "+52w"); the rolling-keys discipline. */
  readonly validity: string;
}

/** Join a user list into the OpenSSH `-n` principals value: comma-separated, no spaces
 *  (`aaron,addison`). The list IS the authorization-binding; the pairing never becomes a
 *  composite identifier (the #8926 / Key-ID N×M lesson). */
export function joinPrincipals(users: readonly string[]): string {
  return users.join(",");
}

/** The result of a sign — the written cert path + its (public) text. No private material. */
export interface SignCertOutput {
  /** Path the `-cert.pub` was written to (next to the device pubkey). */
  readonly certPath: string;
  /** The certificate text (public — safe to print / publish / commit). */
  readonly certText: string;
}

/** Default validity window for a signed device cert — the rolling-keys discipline
 *  (a cert expires; you re-sign). 52 weeks is a conservative pre-cluster default. */
export const DEFAULT_CERT_VALIDITY = "+52w";

/** Where the CA PRIVATE key lives locally (operator-held; NEVER published, NEVER committed). */
export function caPrivateKeyPath(home: string = homedir()): string {
  return join(home, ".config", "zeta", "ca", "ssh_ca_ed25519");
}

/** Where the CA PUBLIC key is committed for git-distribution → fed to `TrustedUserCAKeys`.
 *  This path is REFERENCED by ssh-ca.nix; it LANDS only when the operator runs `ca`. */
export function caPublicKeyPath(repoRoot: string, ca: string): string {
  return join(repoRoot, "maintainers", ca, "ssh-ca.pub");
}

/**
 * The CA dependency disposition for THIS host — the realize-vs-route decision setup-machine
 * makes BEFORE touching anything (Aaron 2026-06-21: setup must REALIZE missing deps, but must
 * NEVER fabricate a SECOND CA when one already exists elsewhere — route to its holder instead).
 * It is a pure function of two facts:
 *
 *   - `localCaPrivateExists` — is the CA PRIVATE key present on THIS host (`~/.config/zeta/ca/`)?
 *   - `committedTrustRoots`  — the committed CA PUBLIC trust roots already in the repo
 *                              (`maintainers/<ca>/ssh-ca.pub`), if any.
 *
 * The three dispositions (fail-SAFE — when in doubt we ROUTE, never fabricate):
 *
 *   - "present"  — THIS host holds the CA private key. The cert can be signed here directly.
 *   - "realize"  — NO local CA private AND NO committed anchor anywhere ⇒ this is a solo /
 *                  first node, so REALIZE its CA here (call `ensureCa`) — and then COMMIT its
 *                  public key, which is what makes it attested (see the trust model below).
 *   - "route"    — NO local CA private BUT a committed anchor EXISTS (that CA lives on ANOTHER
 *                  host) ⇒ DO NOT mint a second CA here. Route: the device cert must be signed
 *                  by the anchor's holder, because the anchor is the key peers already trust.
 *
 * ── THE TRUST MODEL (Aaron 2026-08-01 — correcting an earlier mis-framing in this file) ───────
 * There is NO single trust root in Zeta. The model is fully decentralized: **every node is its
 * own CA.** So a second CA existing is NOT, by itself, a fault — it is the design.
 *
 * What makes a node's CA usable by peers is that it has been **ATTESTED**: its CA public key is
 * COMMITTED to the repo (`maintainers/<ca>/ssh-ca.pub`). The committed key IS the attestation, and
 * the repo (any git remote, or none) carries it — this is git-native, not host-specific. Whoever
 * gates *who may commit an anchor* is the access-control layer, and that is a **forge-host plugin**
 * concern (`src/Core.TypeScript/forge-host/`: github | gitlab | gitea | bitbucket | sourcehut |
 * codeberg), deliberately swappable and never named here.
 * (Same shape as the cert conventions we mirror: git's `allowed_signers` for commit signing,
 * k8s/cert-manager trust bundles, SSH CAs.)
 *
 * So the ACTUAL failure mode this guard prevents is NOT "splitting a trust root" — there is no
 * root to split. It is minting an **UNATTESTED** CA: a key nobody bootstrapped through the
 * GitHub channel, so no peer can verify certs signed by it. That host would hold an orphan
 * identity — invisible to the web of trust, and silently so.
 *
 * Naming caveat: `committedTrustRoots` are **bootstrap anchors**, not PKI roots in the
 * single-root sense. Read the name as "the CA public keys already attested via the repo".
 * Prior art for bootstrapping decentralized identity off a centralized IdP: Sigstore/Fulcio
 * (OIDC identity ⇒ short-lived signing certs), SPIFFE/SPIRE (workload identity), TOFU and the
 * PGP web-of-trust, Zooko's triangle (the tradeoff this pattern navigates).
 *
 * ── TRAJECTORY: NEVER GitHub — the forge is a PLUGIN (Aaron 2026-08-01) ──────────────────────
 * **SPIFFE/SPIRE is the long-term target shape** (workload identity: short-lived SVIDs against
 * trust bundles). Zeta must reach it WITHOUT privileging any host. Aaron: *"never github — we
 * call this a forgehost plugin; we want to be able to run with just cron processes basically one
 * day, or just browser tabs, or completely with github, git-native, or zetadb-native only,
 * decentralized."*
 *
 * **The forge seam already exists and is genuinely host-agnostic:**
 * `src/Core.TypeScript/forge-host/` — a `registerAdapter(pattern, factory)` registry, a
 * `ForgeHost` interface, and `ForgeType` already spanning github | gitlab | gitea | bitbucket |
 * sourcehut | codeberg | unknown, with github AND gitlab adapters shipped. GitHub is one plugin
 * among six, not a dependency.
 *
 * **Where THIS file actually sits — better than "GitHub-bootstrapped":** `resolveCaDisposition`
 * reads `maintainers/<ca>/ssh-ca.pub` **from the working tree**. That is already **git-native**:
 * any git host, a bare remote, or a sneakernet clone satisfies it. The only borrowed authority is
 * **push access control** (who may commit an anchor) — and that is a forge-host plugin concern,
 * not a property of this logic. So do not describe this as "GitHub bootstrap"; describe it as
 * *committed-anchor attestation, with access control delegated to whatever forge plugin is in use*.
 *
 * **Two independent axes to keep separate:**
 *   - *Anchor attestation:* committed anchors (today, git-native) → a Z-set trust fold
 *     (zetadb-native: grant +1 / revoke −1 retraction; current trust = the consolidated fold,
 *     never a desired-state map). ORDER-INDEPENDENCE is what lets that converge with **no
 *     coordinator** — it is precisely the property that removes the central authority. The
 *     primitive is already proven: `SchemaLog` (work-item 081KYWE8Q4008QG0R000H558SH) shows
 *     order-independence, prefix-replay, retraction-cancels, honest idempotency on a ±1 event log.
 *   - *Execution substrate:* a forge's CI → plain **cron processes** → **browser tabs** → nothing
 *     but peers. The trust logic must not assume ANY of these.
 *
 * **Constraint to hold now (already satisfied — keep it that way):** `resolveCaDisposition` is a
 * pure function of (local private key, attested anchors). It names no forge, performs no network
 * IO, and no `ForgeHost` type appears in this file. Swapping the anchor SOURCE (committed file →
 * git object → Z-set fold) must stay a change of caller, never a change of this function.
 * Work-item 081KYXQ3SZN08QG0R002X3DTQM tracks the fold rung.
 *
 * This is the honest seam: the ONLY ambiguous case ("is THIS host the CA holder?") is resolved
 * by the presence of the LOCAL CA private key — a fact this host can see for itself — and we
 * bias to ROUTE (the safe choice) whenever a trust root already exists but the private key does
 * not. No network probe, no guess: realize only when there is provably no CA anywhere yet.
 */
export type CaDisposition = "present" | "realize" | "route";

/** The resolved CA disposition + the facts it was derived from (for an auditable readout). */
export interface CaDispositionResult {
  readonly disposition: CaDisposition;
  /** True iff the CA PRIVATE key is present on THIS host. */
  readonly localCaPrivateExists: boolean;
  /** The committed CA PUBLIC trust-root identities found in the repo (maintainers/<ca>/). */
  readonly committedTrustRoots: readonly string[];
  /** Local path the CA PRIVATE key lives at (never its contents). */
  readonly caPrivatePath: string;
  /** A one-line human-readable rationale for the chosen disposition. */
  readonly rationale: string;
}

/**
 * Resolve the CA disposition for this host — PURE over the two injected facts (the local
 * CA-private presence + the committed trust roots). No IO here; the caller (CLI) gathers the
 * facts through its injected effects and the test injects them directly.
 */
export function resolveCaDisposition(opts: {
  readonly localCaPrivateExists: boolean;
  readonly committedTrustRoots: readonly string[];
  readonly home?: string;
}): CaDispositionResult {
  const caPrivatePath = opts.home === undefined ? caPrivateKeyPath() : caPrivateKeyPath(opts.home);
  const roots = opts.committedTrustRoots;
  if (opts.localCaPrivateExists) {
    return {
      disposition: "present",
      localCaPrivateExists: true,
      committedTrustRoots: roots,
      caPrivatePath,
      rationale: "CA private key present on THIS host — sign the device cert here directly.",
    };
  }
  if (roots.length > 0) {
    return {
      disposition: "route",
      localCaPrivateExists: false,
      committedTrustRoots: roots,
      caPrivatePath,
      rationale:
        `a committed CA trust root exists (${roots.join(", ")}) but no local CA private key — ` +
        "the CA lives on ANOTHER host; ROUTE the cert to the CA holder (do NOT fabricate a 2nd CA).",
    };
  }
  return {
    disposition: "realize",
    localCaPrivateExists: false,
    committedTrustRoots: roots,
    caPrivatePath,
    rationale:
      "no local CA private key AND no committed trust root anywhere — this is a solo / first " +
      "node, so REALIZE the cluster CA here (bootstrap the trust root).",
  };
}

/** Where committed CA PUBLIC trust roots live: maintainers/<ca>/ssh-ca.pub. The realizer scans
 *  this to detect "a CA already exists somewhere" (→ route, never fabricate a second CA). */
export function maintainersDirPath(repoRoot: string): string {
  return join(repoRoot, "maintainers");
}

/** Where a signed device certificate is written — next to the device pubkey it certifies. */
export function certPath(devicePubPath: string): string {
  // ssh-keygen -s names the cert "<base>-cert.pub" where base is the pubkey minus ".pub".
  const base = devicePubPath.endsWith(".pub") ? devicePubPath.slice(0, -4) : devicePubPath;
  return base + "-cert.pub";
}

