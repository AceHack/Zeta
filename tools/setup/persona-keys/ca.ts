/**
 * Sign a per-machine device PUBLIC key into a certificate (`principal=<user>` + machine id +
 * a validity window) via the injected `signCert` door (ssh-keygen -s under the hood) — AGENT-RUN,
 * OPERATOR-APPROVED. The agent EXECUTES the sign; a biometric confirm is the operator's
 * AUTHORIZATION (signing CONSUMES the CA private key, so it must be approved). The CA private
 * key is consumed by the runner; it is never read into this process.
 *
 * Reads the machine's PUBLIC key from `devicePubPath` (the machine.ts registry seam —
 * `machines/<host>.pub`, the USER-INDEPENDENT machine registry). This cert is the ONLY place
 * the (user × machine) pair is named: a PURE machine key (host-only) signed with
 * `principal=<user>` (pure-key model, Aaron 2026-06-21). Fail-closed: a missing CA or device
 * key returns a typed `no-ca` / `no-device-key` (no partial work) and NEVER prompts.
 * `--dry-run` signs NOTHING and never prompts.
 *
 * BIOMETRIC GATE + FAIL-CLOSED: when a real sign is about to happen (CA + device key present,
 * not dry-run), `biometricAuth()` MUST return ok:true first. On ok:false the run aborts
 * ("aborted-biometric") and `signCert` is NEVER invoked — NO cert is produced.
 *
 * @param biometricAuth the SHARED approval gate (biometric.ts). Required for the real-sign path.
 */
export async function signMachineCert(
  fx: CaEffects,
  opts: {
    /** The USER the cert binds to (the `-n` principal — trust anchored at the user). A single
     *  owner; for a co-owned machine pass `users` instead (this is the one-element shorthand). */
    readonly user?: string;
    /** The authorized USER LIST for a (possibly multi-owner) machine — `["aaron","addison"]`.
     *  Takes precedence over `user`; the comma-joined value becomes the `-n` principals. A
     *  one-element list is the single-owner path. EXACTLY ONE of `user` / `users` is required;
     *  `users` must be non-empty. The (user × machine) pairing lives in this LIST — never a
     *  composite identifier (the #8926 / Key-ID N×M lesson). */
    readonly users?: readonly string[];
    /** A machine id for the cert identity (`-I`), e.g. the sanitized hostname. */
    readonly machineId: string;
    /** Path to the per-machine device PUBLIC key to sign (the registry `machines/<host>.pub`). */
    readonly devicePubPath: string;
    readonly home?: string;
    /** Validity window (OpenSSH `-V` form). Defaults to DEFAULT_CERT_VALIDITY. */
    readonly validity?: string;
    readonly dryRun?: boolean;
    /** SHARED biometric approval door — required for the real sign path (fail-closed). */
    readonly biometricAuth?: BiometricAuth;
  },
): Promise<CertResult> {
  const caPrivatePath = opts.home === undefined ? caPrivateKeyPath() : caPrivateKeyPath(opts.home);
  const validity = opts.validity ?? DEFAULT_CERT_VALIDITY;
  // Resolve the authorized user LIST: `users` (multi-owner) wins; else the single `user`. The
  // (user × machine) binding is this LIST, never a composite id. Fail-closed on a degenerate
  // request (neither given, or an empty `users`) — we never sign a cert with NO principal.
  const users: readonly string[] =
    opts.users !== undefined && opts.users.length > 0 ? opts.users : opts.user !== undefined ? [opts.user] : [];
  if (users.length === 0) {
    throw new Error("signMachineCert: provide a non-empty `users` list or a single `user`.");
  }
  const principal = joinPrincipals(users); // the exact `-n` value (`aaron,addison`)
  // Key ID names the certified SUBJECT = the machine key, so it is the machine id ALONE — NOT
  // `user@machine`. A composite user×machine Key ID is the N×M smell (Aaron, 2026-06-21; same
  // shape as the #8926 hybrid-key error): it would mint a distinct cert per (user, machine) pair
  // → O(N×M) certs. The user binding lives in the PRINCIPAL (`-n`, below), so one cert per machine
  // (Key ID = machine, principals = authorized user(s)) keeps it O(N+M). Multi-user on a shared
  // box = re-sign the one machine cert with more principals (still one cert per machine).
  const certId = opts.machineId;
  const outPath = certPath(opts.devicePubPath);
  const dryRun = opts.dryRun === true;

  const base = {
    caPrivatePath,
    devicePubPath: opts.devicePubPath,
    certPath: outPath,
    certId,
    principals: users,
    principal,
    validity,
  };

  // Fail-closed presence checks (BEFORE any work, BEFORE any prompt) — a missing CA or device
  // key is a typed no-op, never a partial sign. (Checked even on dry-run so the plan is honest.)
  if (!fx.exists(caPrivatePath)) {
    return { ...base, dryRun, action: "no-ca" };
  }
  if (!fx.exists(opts.devicePubPath)) {
    return { ...base, dryRun, action: "no-device-key" };
  }

  if (dryRun) {
    return { ...base, dryRun: true, action: "would-sign" };
  }

  // BIOMETRIC GATE — fail-closed. A real sign consumes the CA private key; require approval.
  // The cert-signing brief. `principal` and `validity` below are the SAME values handed to
  // `fx.signCert` — the prompt is derived from them, never authored beside them.
  //
  // NOTE THE CLASSIFICATION, and do not "fix" it by relabelling: signing a leaf certificate
  // under a CA this node already holds IS `issue-leaf-svid`, which `ceremony-gate.ts`
  // classifies UNATTENDED — "adds no party and no capability". So this call site raises a
  // biometric prompt for work the repo's own policy says needs no human, and the brief will
  // say so out loud on the prompt (the NOT GATED / MISMATCH arm of `renderCeremonyBrief`).
  //
  // That is deliberate. Prompting for routine work is the mechanism that teaches an operator
  // to approve reflexively, and the honest label is what makes the mismatch reviewable
  // instead of invisible. Whether to keep the prompt, or drop it and let the certificate be
  // issued unattended under the one approval the CALLER already took, is a policy call for
  // whoever owns this gate — not something a display layer may quietly decide.
  const certBrief: CeremonyBrief = {
    operation: "issue-leaf-svid",
    summary: "Sign a device certificate with the CA private key",
    subjects: [
      { label: "machine", value: opts.machineId },
      { label: "principals", value: principal },
      { label: "device key", value: opts.devicePubPath },
      { label: "signing CA", value: caPrivatePath },
      { label: "validity", value: validity },
    ],
    ifDeclined:
      "no certificate is signed and nothing is written; this command exits reporting " +
      "'aborted-biometric'. Any certificate this machine already holds keeps working.",
    ...requestedBy(fx.requester),
  };
  fx.notify?.(renderCeremonyBrief(certBrief));
  const biometric = await requireBiometric(opts.biometricAuth, ceremonyPromptLine(certBrief));
  if (!biometric.ok) {
    return { ...base, dryRun: false, action: "aborted-biometric", biometric };
  }

  const out = fx.signCert({
    caKeyPath: caPrivatePath,
    devicePubPath: opts.devicePubPath,
    certId,
    principals: users,
    validity,
  });
  return { ...base, dryRun: false, action: "signed", certText: out.certText, biometric };
}

function dirOf(p: string): string {
  const i = p.lastIndexOf("/");
  return i >= 0 ? p.slice(0, i) : ".";
}

/** The REAL host effects (used by the CLI). ssh-keygen generates the CA in-process; the CA
 *  PRIVATE key file is created under umask 077 by ssh-keygen and is never read by us. */
export function realEffects(): CaEffects {
  return {
    ...realBriefEffects(),
    exists: (p) => existsSync(p),
    readText: (p) => readFileSync(p, "utf8"),
    writeText: (p, c) => writeFileSync(p, c, { mode: 0o644 }),
    mkdirp: (p) => mkdirSync(p, { recursive: true }),
    genCa: (caKeyPath, comment) => {
      mkdirSync(dirOf(caKeyPath), { recursive: true, mode: 0o700 });
      const prevUmask = process.umask(0o077); // CA private key must not be group/other readable
      try {
        // ssh-keygen generates the CA key itself — no secret on argv. -N "" = no passphrase
        // (the operator may add one); the private file stays LOCAL under umask 077.
        const r = spawnSync("ssh-keygen", ["-t", "ed25519", "-N", "", "-f", caKeyPath, "-C", comment], {
          encoding: "utf8",
          stdio: ["ignore", "pipe", "pipe"],
        });
        if (r.status !== 0) {
          throw new Error(`ssh-keygen (CA) failed (status ${r.status ?? "signal"}): ${r.stderr ?? ""}`);
        }
      } finally {
        process.umask(prevUmask);
      }
      // Read back ONLY the public half.
      return readFileSync(caKeyPath + ".pub", "utf8");
    },
    signCert: (req) => {
      // ssh-keygen -s <ca> -I <id> -n aaron,addison -V <validity> <devicePub>
      // The `-n` value is the comma-joined principals LIST (one OpenSSH cert authorizing all
      // listed users); Key ID (`-I`) is machine-only. Writes "<devicePub base>-cert.pub" (public).
      // The CA private key is read by ssh-keygen, never by us; the cert is public output.
      const r = spawnSync(
        "ssh-keygen",
        [
          "-s",
          req.caKeyPath,
          "-I",
          req.certId,
          "-n",
          joinPrincipals(req.principals),
          "-V",
          req.validity,
          req.devicePubPath,
        ],
        { encoding: "utf8", stdio: ["ignore", "pipe", "pipe"] },
      );
      if (r.status !== 0) {
        throw new Error(`ssh-keygen -s (sign) failed (status ${r.status ?? "signal"}): ${r.stderr ?? ""}`);
      }
      const out = certPath(req.devicePubPath);
      return { certPath: out, certText: readFileSync(out, "utf8") };
    },
  };
}
