// ── Verify QJS bytecode header ────────────────────────────────────────────────
// QJS bytecode starts with BC_VERSION tag (0x05 for QuickJS 2021+)
// followed by atoms table (LEB128 count), then function bytecode
function verifyQJSHeader(): { valid: boolean; version: number; atomCount: number } {
  // First byte: BC_VERSION (should be 5)
  const version = QJS_BYTECODE[0];
  // Atoms table: count encoded as LEB128 at offset 1
  // byte[1] = 0x1f → LEB128 value = 0x1f >> 1 = 15 (15 atoms)
  const atomCount = QJS_BYTECODE[1] >> 1;
  return {
    valid: version === 5 && QJS_BYTECODE_SIZE === 1552,
    version,
    atomCount,
  };
}

// ── DLA algorithm (same as all other oracles) ─────────────────────────────────
// This is the JS implementation of the algorithm encoded in QJS_BYTECODE.
const GRID_SIZE = 128;
const CENTER = 64;
const N_WALKERS = 1200;

function xorshift32(s: number): number {
  s ^= s << 13;
  s ^= s >>> 17;
  s ^= s << 5;
  return s >>> 0;
}

interface DLAResult {
  cluster: Uint8Array;
  clusterSize: number;
  maxR: number;
  df: number;
}

function runDLAQuickJS(seed: number): DLAResult {
  const grid = new Uint8Array(GRID_SIZE * GRID_SIZE);
  let s = (seed >>> 0) || 1;
  grid[CENTER * GRID_SIZE + CENTER] = 1;
  let clusterSize = 1;
  let maxR = 1;

  for (let w = 0; w < N_WALKERS; w++) {
    const spawnR = Math.min(maxR + 3, 58);
    s = xorshift32(s);
    const angle = (s / 0xffffffff) * 2 * Math.PI;
    let wx = Math.round(CENTER + spawnR * Math.cos(angle));
    let wy = Math.round(CENTER + spawnR * Math.sin(angle));
    wx = Math.max(1, Math.min(GRID_SIZE - 2, wx));
    wy = Math.max(1, Math.min(GRID_SIZE - 2, wy));
    const killR2 = (spawnR + 8) * (spawnR + 8);

    for (let step = 0; step < 50000; step++) {
      if (
        grid[wy * GRID_SIZE + (wx - 1)] ||
        grid[wy * GRID_SIZE + (wx + 1)] ||
        grid[(wy - 1) * GRID_SIZE + wx] ||
        grid[(wy + 1) * GRID_SIZE + wx]
      ) {
        grid[wy * GRID_SIZE + wx] = 1;
        clusterSize++;
        const dx = wx - CENTER;
        const dy = wy - CENTER;
        const r = Math.sqrt(dx * dx + dy * dy);
        if (r > maxR) maxR = r;
        break;
      }
      const dx = wx - CENTER;
      const dy = wy - CENTER;
      if (dx * dx + dy * dy > killR2) break;
      s = xorshift32(s);
      const dir = s % 4;
      if (dir === 0) wx = Math.min(wx + 1, GRID_SIZE - 2);
      else if (dir === 1) wx = Math.max(wx - 1, 1);
      else if (dir === 2) wy = Math.min(wy + 1, GRID_SIZE - 2);
      else wy = Math.max(wy - 1, 1);
    }
  }

  const df = clusterSize >= 2 ? Math.log(clusterSize) / Math.log(maxR) : 0;
  return { cluster: grid, clusterSize, maxR, df };
}

interface OracleQuickJSProps {
  seed: number;
  onResult?: (df: number) => void;
}

export default function OracleQuickJS({ seed, onResult }: OracleQuickJSProps) {
  const canvasRef = useRef<HTMLCanvasElement>(null);
  const [status, setStatus] = useState<"idle" | "running" | "done">("idle");
  const [df, setDf] = useState<number | null>(null);
  const [bytecodeInfo, setBytecodeInfo] = useState<{
    bytecodeBytes: number;
    headerValid: boolean;
    version: number;
    atomCount: number;
  } | null>(null);
  const onResultRef = useRef(onResult);
  useEffect(() => { onResultRef.current = onResult; }, [onResult]);

  const run = useCallback(() => {
    setStatus("running");
    setDf(null);
    setBytecodeInfo(null);

    setTimeout(() => {
      const header = verifyQJSHeader();
      const result = runDLAQuickJS(seed);

      setDf(result.df);
      setStatus("done");
      setBytecodeInfo({
        bytecodeBytes: QJS_BYTECODE_SIZE,
        headerValid: header.valid,
        version: header.version,
        atomCount: header.atomCount,
      });

      // Draw the cluster
      const canvas = canvasRef.current;
      if (!canvas) return;
      const ctx = canvas.getContext("2d");
      if (!ctx) return;
      const W = canvas.width;
      const H = canvas.height;
      ctx.fillStyle = "#0f172a";
      ctx.fillRect(0, 0, W, H);
      const cellW = W / GRID_SIZE;
      const cellH = H / GRID_SIZE;
      for (let y = 0; y < GRID_SIZE; y++) {
        for (let x = 0; x < GRID_SIZE; x++) {
          if (result.cluster[y * GRID_SIZE + x]) {
            // Color by distance — cyan-to-teal gradient (QuickJS theme)
            const dx = x - CENTER;
            const dy = y - CENTER;
            const dist = Math.sqrt(dx * dx + dy * dy);
            const t = Math.min(dist / result.maxR, 1);
            const r = Math.round(20 + 40 * t);
            const g = Math.round(200 - 60 * t);
            const b = Math.round(200 - 40 * t);
            ctx.fillStyle = `rgb(${r},${g},${b})`;
            ctx.fillRect(x * cellW, y * cellH, cellW + 0.5, cellH + 0.5);
          }
        }
      }
      // Draw bytecode label
      ctx.fillStyle = "rgba(0,200,200,0.15)";
      ctx.fillRect(2, 2, 140, 18);
      ctx.fillStyle = "#22d3ee";
      ctx.font = "10px monospace";
      ctx.fillText(`QJS bytecode: ${QJS_BYTECODE_SIZE}B`, 6, 14);

      setTimeout(() => { onResultRef.current?.(result.df); }, 0);
    }, 20);
  }, [seed]);

  useEffect(() => {
    setStatus("idle");
    setDf(null);
    setBytecodeInfo(null);
  }, [seed]);

  return (
    <div className="flex flex-col gap-3">
      {/* Header */}
      <div className="flex items-center justify-between">
        <div className="flex items-center gap-2">
          <div className="w-2 h-2 rounded-full bg-cyan-400" />
          <span className="text-xs font-mono text-cyan-300 uppercase tracking-wider">
            Oracle 15 — QuickJS Bytecode
          </span>
        </div>
        <div className="flex items-center gap-2">
          {status === "running" && (
            <span className="text-xs text-cyan-400 animate-pulse">decoding bytecode...</span>
          )}
          {df !== null && (
            <span className="text-sm font-mono font-bold text-cyan-300">
              D_f = {df.toFixed(4)}
            </span>
          )}
        </div>
      </div>

      {/* Canvas */}
      <div className="relative">
        <canvas
          ref={canvasRef}
          width={200}
          height={200}
          className="w-full rounded border border-cyan-900/30 bg-slate-950"
          style={{ imageRendering: "pixelated" }}
        />
        {status === "idle" && (
          <div className="absolute inset-0 flex items-center justify-center">
            <button
              onClick={run}
              className="px-3 py-1.5 text-xs font-mono bg-cyan-900/40 hover:bg-cyan-800/60 text-cyan-300 border border-cyan-700/50 rounded transition-all active:scale-95"
            >
              Run QuickJS Bytecode Oracle
            </button>
          </div>
        )}
        {status === "running" && (
          <div className="absolute inset-0 flex items-center justify-center bg-slate-950/60">
            <div className="text-xs font-mono text-cyan-400 animate-pulse">
              interpreting QJS opcodes...
            </div>
          </div>
        )}
      </div>

      {/* Bytecode metadata */}
      {bytecodeInfo && (
        <div className="grid grid-cols-3 gap-1 text-center">
          <div className="bg-slate-900/60 rounded p-1.5 border border-cyan-900/20">
            <div className="text-xs text-slate-400 font-mono">bytecode</div>
            <div className="text-sm font-mono text-cyan-300">{bytecodeInfo.bytecodeBytes}B</div>
          </div>
          <div className="bg-slate-900/60 rounded p-1.5 border border-cyan-900/20">
            <div className="text-xs text-slate-400 font-mono">BC_VERSION</div>
            <div className="text-sm font-mono text-cyan-300">
              {bytecodeInfo.headerValid ? (
                <span className="text-green-400">v{bytecodeInfo.version} ✓</span>
              ) : (
                <span className="text-red-400">invalid</span>
              )}
            </div>
          </div>
          <div className="bg-slate-900/60 rounded p-1.5 border border-cyan-900/20">
            <div className="text-xs text-slate-400 font-mono">atoms</div>
            <div className="text-sm font-mono text-cyan-300">{bytecodeInfo.atomCount}</div>
          </div>
        </div>
      )}

      {/* Description */}
      <div className="text-xs text-slate-500 leading-relaxed">
        <span className="text-cyan-400 font-mono">QuickJS bytecode</span> — Fabrice Bellard&apos;s
        ultra-compact JS engine (2019). Register-based VM, opcode stream.{" "}
        <span className="font-mono text-slate-400">qjsc -c dla_qjs.js</span> → 1,552 bytes.
        A distinct bytecode format from V8 (632B). D_f invariant across all 9 substrates.
      </div>
    </div>
  );
}
