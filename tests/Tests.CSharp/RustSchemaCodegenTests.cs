using System;
using System.Collections.Generic;
using Xunit;
using Zeta.Core.CSharp;

namespace Zeta.Tests.CSharp;

/// <summary>
/// Tests for <see cref="RustSchemaCodegen"/> — the Rust leg of "one IR, a typed surface per
/// oracle." The SAME <see cref="TypeSchema"/> that <see cref="SchemaCodegen"/> renders to a C#
/// record renders here to a Rust struct, with Rust idioms (snake_case fields, <c>Option&lt;T&gt;</c>).
/// </summary>
public class RustSchemaCodegenTests
{
    private static readonly TypeSchema ImdbName = new(
        "Zeta.Generated",
        "ImdbName",
        new List<SchemaField>
        {
            new("Nconst", "string"),
            new("PrimaryName", "string"),
            new("BirthYear", "int?"),
            new("DeathYear", "int?"),
        });

    [Fact]
    public void GeneratesExpectedRustStruct()
    {
        string src = RustSchemaCodegen.Generate(ImdbName);
        const string Expected =
            "// @generated by Zeta.Core.CSharp.RustSchemaCodegen from a zeta type schema. Do not edit.\n"
            + "#[derive(Debug, Clone, PartialEq)]\n"
            + "pub struct ImdbName {\n"
            + "    pub nconst: String,\n"
            + "    pub primary_name: String,\n"
            + "    pub birth_year: Option<i32>,\n"
            + "    pub death_year: Option<i32>,\n"
            + "}\n";
        Assert.Equal(Expected, src);
    }

    [Fact]
    public void SameSchemaFeedsBothCSharpAndRust()
    {
        // The north-star property: ONE IR, two typed surfaces. Both succeed on the same value.
        Assert.Contains("public sealed record ImdbName(", SchemaCodegen.Generate(ImdbName), StringComparison.Ordinal);
        Assert.Contains("pub struct ImdbName {", RustSchemaCodegen.Generate(ImdbName), StringComparison.Ordinal);
    }

    [Fact]
    public void IsDeterministic()
    {
        Assert.Equal(RustSchemaCodegen.Generate(ImdbName), RustSchemaCodegen.Generate(ImdbName));
    }

    [Fact]
    public void MapsNullableToOptionAndSnakeCases()
    {
        var schema = new TypeSchema("Zeta.Generated", "Title", new List<SchemaField> { new("StartYear", "int?") });
        Assert.Contains("pub start_year: Option<i32>,", RustSchemaCodegen.Generate(schema), StringComparison.Ordinal);
    }

    [Fact]
    public void UnknownTypeTokenThrows()
    {
        var schema = new TypeSchema("Zeta.Generated", "Bad", new List<SchemaField> { new("X", "decimal") });
        Assert.Throws<NotSupportedException>(() => RustSchemaCodegen.Generate(schema));
    }
}
