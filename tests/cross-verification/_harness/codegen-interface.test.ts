import { describe, test, expect } from "bun:test";
import {
  emitCSharp, emitTypeScript, emitRust, emitFSharp, emitPython, emitGo, emitQSharp,
  type InterfaceIr
} from "./codegen-interface";
import { readFileSync } from "node:fs";
import { join } from "node:path";

const irDir = join(import.meta.dir, "../zeta-ir-v2/interfaces");
const semiring: InterfaceIr = JSON.parse(readFileSync(join(irDir, "semiring.ir.json"), "utf-8"));
const ring: InterfaceIr = JSON.parse(readFileSync(join(irDir, "ring.ir.json"), "utf-8"));
const starRing: InterfaceIr = JSON.parse(readFileSync(join(irDir, "star-ring.ir.json"), "utf-8"));
const zsetIsa: InterfaceIr = JSON.parse(readFileSync(join(irDir, "zset-isa.ir.json"), "utf-8"));
const gset: InterfaceIr = JSON.parse(readFileSync(join(irDir, "gset.ir.json"), "utf-8"));
const zset: InterfaceIr = JSON.parse(readFileSync(join(irDir, "zset.ir.json"), "utf-8"));
const boundedGset: InterfaceIr = JSON.parse(readFileSync(join(irDir, "bounded-gset.ir.json"), "utf-8"));
const boundedZset: InterfaceIr = JSON.parse(readFileSync(join(irDir, "bounded-zset.ir.json"), "utf-8"));
const heatSink: InterfaceIr = JSON.parse(readFileSync(join(irDir, "heat-sink.ir.json"), "utf-8"));
const database: InterfaceIr = JSON.parse(readFileSync(join(irDir, "database.ir.json"), "utf-8"));

describe("codegen-interface — ISemiring", () => {
  test("C# emits correct interface with inheritance", () => {
    const cs = emitCSharp(semiring);
    expect(cs).toContain("public interface ISemiring<TWeight>");
    expect(cs).toContain("TWeight Zero { get; }");
    expect(cs).toContain("TWeight Add(TWeight a, TWeight b)");
    expect(cs).not.toContain("TWeight Negate(TWeight a)"); // 081KWG9JQ9H: Negate lives in IRing
    expect(cs).toContain("namespace Zeta.Core");
  });

  test("TypeScript emits correct interface", () => {
    const ts = emitTypeScript(semiring);
    expect(ts).toContain("export interface ISemiring<TWeight>");
    expect(ts).toContain("readonly Zero: TWeight");
    expect(ts).toContain("Add(a: TWeight, b: TWeight): TWeight");
  });

  test("Rust emits correct trait", () => {
    const rs = emitRust(semiring);
    expect(rs).toContain("pub trait ISemiring<TWeight>");
    expect(rs).toContain("fn zero(&self) -> TWeight");
    expect(rs).toContain("fn add(&self, a: TWeight, b: TWeight) -> TWeight");
  });

  test("F# emits correct abstract type", () => {
    const fsx = emitFSharp(semiring);
    expect(fsx).toContain("type ISemiring<'TWeight>");
    expect(fsx).toContain("abstract member Zero: 'TWeight");
    expect(fsx).toContain("abstract member Add: 'TWeight * 'TWeight -> 'TWeight");
  });

  test("Python emits correct Protocol with TypeVar", () => {
    const py = emitPython(semiring);
    expect(py).toContain('TWeight = TypeVar("TWeight")');
    expect(py).toContain("class ISemiring(Protocol, Generic[TWeight])");
    expect(py).toContain("def add(self, a: TWeight, b: TWeight) -> TWeight");
  });

  test("Go emits correct interface with generics", () => {
    const go = emitGo(semiring);
    expect(go).toContain("type ISemiring[TWeight any] interface");
    expect(go).toContain("Add(a TWeight, b TWeight) TWeight");
  });

  test("all 7 targets contain the GENERATED marker", () => {
    const all = [emitCSharp, emitTypeScript, emitRust, emitFSharp, emitPython, emitGo, emitQSharp];
    for (const emit of all) {
      expect(emit(semiring)).toContain("GENERATED by codegen-interface.ts");
    }
  });
});

