describe("codegen-interface — IStarRing (with inheritance + laws)", () => {
  test("C# includes variance annotation (invariant = no prefix)", () => {
    const cs = emitCSharp(starRing);
    // Invariant means no `out`/`in` prefix
    expect(cs).toContain("IStarRing<TWeight>");
    expect(cs).not.toContain("out TWeight");
    expect(cs).not.toContain("in TWeight");
  });

  test("C# includes extends clause", () => {
    const cs = emitCSharp(starRing);
    expect(cs).toContain(": IRing<TWeight>"); // 081KWG9JQ9H rebase
  });

  test("C# includes laws as XML remarks", () => {
    const cs = emitCSharp(starRing);
    expect(cs).toContain("Conj(Conj(a)) = a");
    expect(cs).toContain("reverses order");
  });

  test("TypeScript includes extends clause", () => {
    const ts = emitTypeScript(starRing);
    expect(ts).toContain("extends IRing<TWeight>"); // 081KWG9JQ9H rebase
  });

  test("Rust includes supertrait bound", () => {
    const rs = emitRust(starRing);
    expect(rs).toContain(": IRing"); // 081KWG9JQ9H rebase
  });

  test("Go includes embedded interface", () => {
    const go = emitGo(starRing);
    expect(go).toContain("IRing[TWeight]"); // 081KWG9JQ9H rebase
  });

  test("Conj method present in all targets", () => {
    expect(emitCSharp(starRing)).toContain("Conj");
    expect(emitTypeScript(starRing)).toContain("Conj");
    expect(emitRust(starRing)).toContain("conj");
    expect(emitFSharp(starRing)).toContain("Conj");
    expect(emitPython(starRing)).toContain("conj");
    expect(emitGo(starRing)).toContain("Conj");
    expect(emitQSharp(starRing)).toContain("Conj");
  });
});

describe("codegen-interface — variance (covariant interface)", () => {
  const covariantIr: InterfaceIr = {
    schema: "zeta-ir-v2-interface",
    name: "IFunctor",
    typeParams: [{ name: "T", variance: "covariant" }],
    members: [
      { name: "Map", kind: "method", params: [{ name: "f", type: "(T) => T" }], returns: "IFunctor<T>", doc: "Lift a function over the container." }
    ],
    doc: "Functor — covariant container.",
  };

  test("C# emits 'out T' for covariant", () => {
    const cs = emitCSharp(covariantIr);
    expect(cs).toContain("IFunctor<out T>");
  });

  test("Python emits TypeVar with covariant=True", () => {
    const py = emitPython(covariantIr);
    expect(py).toContain('T = TypeVar("T", covariant=True)');
  });

  test("Rust/Go/F# don't have explicit variance syntax (structural)", () => {
    // These languages handle variance structurally, not declaratively
    const rs = emitRust(covariantIr);
    const go = emitGo(covariantIr);
    // Just verify they compile without variance annotations in the trait/interface
    expect(rs).toContain("pub trait IFunctor<T>");
    expect(go).toContain("type IFunctor[T any] interface");
  });
});

