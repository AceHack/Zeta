function main() {
    const rootDir = path.resolve(__dirname, '../../..');
    const yamlPath = path.join(rootDir, 'docs/zeta-id-v1-layout.yaml');
    const fields = parseYaml(yamlPath);
    console.log(`Parsed ${fields.length} fields from ${yamlPath}`);
    // Write TS
    const tsPath = path.join(rootDir, 'src/Core.TypeScript/zeta-id/zeta-id.gen.ts');
    fs.writeFileSync(tsPath, generateTS(fields), 'utf-8');
    console.log(`Wrote TS to ${tsPath}`);
    // Write F#
    const fsPath = path.join(rootDir, 'src/Core.FSharp.ZetaId/GeneratedBitLayout.fs');
    fs.writeFileSync(fsPath, generateFSharp(fields), 'utf-8');
    console.log(`Wrote F# to ${fsPath}`);
    // Write C#
    const csPath = path.join(rootDir, 'src/Core.CSharp.ZetaId/GeneratedBitLayout.cs');
    fs.writeFileSync(csPath, generateCSharp(fields), 'utf-8');
    console.log(`Wrote C# to ${csPath}`);
    // Write Rust
    const rsPath = path.join(rootDir, 'src/Core.Rust.ZetaId/src/bit_layout.gen.rs');
    fs.writeFileSync(rsPath, generateRust(fields), 'utf-8');
    console.log(`Wrote Rust to ${rsPath}`);
    // Write Go
    const goPath = path.join(rootDir, 'src/Core.Go/zeta_id/zeta_id.gen.go');
    fs.writeFileSync(goPath, generateGo(fields), 'utf-8');
    console.log(`Wrote Go to ${goPath}`);
    // Write Python
    const pyPath = path.join(rootDir, 'src/Core.Python/src/zeta/zeta_id_gen.py');
    fs.writeFileSync(pyPath, generatePython(fields), 'utf-8');
    console.log(`Wrote Python to ${pyPath}`);
    console.log('Running formatters on generated code...');
    try {
        execSync(`npx prettier --write "${tsPath}"`);
        execSync(`go fmt "${goPath}"`);
        execSync(`cargo fmt --manifest-path "${path.join(rootDir, 'src/Core.Rust.ZetaId/Cargo.toml')}"`);
        const pyVenvRuff = path.join(rootDir, 'src/Core.Python/.venv/bin/ruff');
        if (fs.existsSync(pyVenvRuff)) {
            execSync(`"${pyVenvRuff}" format "${pyPath}"`);
        }
    }
    catch (err) {
        console.warn('Warning: Layout formatters had issues:', err);
    }
    console.log('Codegen successfully completed across 6 languages.');
}
main();
