import * as fs from "fs";
import * as path from "path";
import { execSync } from "child_process";
import { parse as parseYaml } from "../yaml/dom";
import { fromYamlValue, canonicalYaml } from "../dynamic-value/yaml";
function parseYamlFile(filePath) {
    const content = fs.readFileSync(filePath, "utf-8");
    const parseRes = parseYaml(content);
    if (!parseRes.ok) {
        throw new Error(`YAML syntax error in ${filePath}: ${parseRes.feedback}`);
    }
    const decodeRes = fromYamlValue(parseRes.value, 0);
    if (!decodeRes.ok) {
        throw new Error(`YAML decode error in ${filePath}: ${decodeRes.error}`);
    }
    const dv = decodeRes.value;
    if (dv.t !== "obj") {
        throw new Error(`Expected YAML root to be a map (Object), got: ${dv.t}`);
    }
    const entriesPair = dv.v.find(([k]) => k === "entries");
    if (!entriesPair) {
        throw new Error(`Expected 'entries' key in complexity registry YAML.`);
    }
    const entriesVal = entriesPair[1];
    if (entriesVal.t !== "arr") {
        throw new Error(`Expected 'entries' to be a sequence (Array), got: ${entriesVal.t}`);
    }
    const entries = [];
    for (const item of entriesVal.v) {
        if (item.t !== "obj") {
            throw new Error(`Expected each entry in 'entries' to be a map, got: ${item.t}`);
        }
        const entry = {};
        for (const [k, val] of item.v) {
            let valStr = "";
            if (val.t === "str") {
                valStr = val.v;
            }
            else if (val.t === "int") {
                valStr = val.v;
            }
            else if (val.t === "bool") {
                valStr = val.v ? "true" : "false";
            }
            else if (val.t === "null") {
                valStr = "null";
            }
            else {
                throw new Error(`Expected entry field ${k} to be a primitive scalar, got: ${val.t}`);
            }
            if (k === "artifact")
                entry.artifact = valStr;
            else if (k === "op")
                entry.op = valStr;
            else if (k === "time")
                entry.time = valStr;
            else if (k === "space")
                entry.space = valStr;
            else if (k === "by")
                entry.by = valStr;
        }
        if (!entry.artifact || !entry.op || !entry.time || !entry.space || !entry.by) {
            throw new Error(`Missing fields in entry: ${JSON.stringify(entry)}`);
        }
        entries.push(entry);
    }
    // Canonicalize the source file itself
    const canonicalRes = canonicalYaml(dv);
    if (!canonicalRes.ok) {
        throw new Error(`Failed to canonicalize DynamicValue YAML: ${canonicalRes.error}`);
    }
    if (canonicalRes.value !== content) {
        console.log(`Re-formatting ${filePath} to canonical format...`);
        fs.writeFileSync(filePath, canonicalRes.value, "utf-8");
    }
    return entries;
}
function generateFSharp(entries) {
    let listStr = "        Map.ofList\n            [";
    entries.forEach((e, idx) => {
        if (idx === 0) {
            listStr += ` ("${e.artifact}", "${e.op}"), c "${e.time}" "${e.space}" ${e.by}\n`;
        }
        else {
            listStr += `              ("${e.artifact}", "${e.op}"), c "${e.time}" "${e.space}" ${e.by}\n`;
        }
    });
    listStr = listStr.trimEnd() + " ]";
    return `namespace Zeta.Core

// Auto-generated by src/Core.TypeScript/complexity/complexity-generator.ts. Do not edit.

/// ComplexityRegistry — **Big-O is REQUIRED on the shelf: proven or derived, never unstated**
/// (Aaron 2026-06-11: "Big-O complexity should be required to be proven on all of these, or derived
/// by our engine — not left unstated. Probably per operation. The math team will need to help — space
/// AND time, memory and compute, for BUDGETING. Also: keep up with any ENTROPY it may hold — it
/// doesn't have to hold it, but it may — internal save state, maybe identities if an AI wants.")
///
/// Per (artifact, operation): time + space, each with PROVENANCE — \`Proven\` (a written proof/test),
/// \`Derived\` (the engine computed it), or implicitly UNSTATED (absent from the table) — and
/// \`unstated\` is the budget lint: it lists every registered artifact whose costs are missing. The
/// declarations below are the first pass (honest provenance: mostly Derived-by-inspection; the math
/// team — Hiroshi's asymptotic lane — upgrades Derived→Proven). ENTROPY HELD is the optional
/// declaration: an artifact MAY hold entropy (save state, identity) and saying so is part of its
/// honest surface (bounded uncertainty: even the holding is declared).
[<RequireQualifiedAccess>]
module ComplexityRegistry =

    type Provenance =
        | Proven
        | Derived

    /// One operation's declared costs: canonical Big-O strings + provenance.
    type Cost =
        { Time: string
          Space: string
          By: Provenance }

    let private c t s by = { Time = t; Space = s; By = by }

    /// The table: (artifact-name, operation) → cost. First pass, derived by inspection — the math
    /// team's docket is the upgrade path (Derived → Proven, per operation).
    let declared: Map<string * string, Cost> =
${listStr}

    /// THE BUDGET LINT: every registered artifact (generators + layouts + indexes + schemes) whose
    /// costs are entirely UNSTATED. Empty list = the requirement holds across the shelf.
    /// THE SEARCHABLE SHAPE of an O-string (Aaron 2026-06-11: "make sure we can search by big O
    /// later… constrain function selection by how long it takes — we have TIME too, not just
    /// memory"). Degree = the count of multiplied VARIABLE factors in the dominant '+' term
    /// (n²=2, n·k=2, w·h·sources=3, steps=1, 1=0); Logs counted separately (no pretended total
    /// order between n·log n and n² beyond degree — honesty over cleverness). Numeric factors
    /// (the 2 in 2·sim) don't count. Unparseable ⇒ None: refusal, never a guess.
    type OShape = { Degree: int; Logs: int }

    let parseO (o: string) : OShape option =
        let inner =
            let s = o.Trim()
            if s.StartsWith "O(" && s.EndsWith ")" then Some(s.Substring(2, s.Length - 3)) else None
        match inner with
        | None -> None
        | Some body ->
            let termShape (term: string) : OShape option =
                let factors =
                    term.Split([| '·'; '*' |])
                    |> Array.map (fun f -> f.Trim())
                    |> Array.filter (fun f -> f.Length > 0)
                if factors.Length = 0 then None
                else
                    let mutable deg = 0
                    let mutable logs = 0
                    let mutable ok = true
                    for f in factors do
                        if f |> Seq.forall System.Char.IsDigit then () // numeric factor: free
                        elif f.StartsWith "log" then logs <- logs + 1
                        elif f.EndsWith "²" then deg <- deg + 2
                        elif f.EndsWith "³" then deg <- deg + 3
                        elif f |> Seq.forall (fun ch -> System.Char.IsLetterOrDigit ch || ch = '-' || ch = '|' || ch = 'Δ') then
                            deg <- deg + 1
                        else ok <- false
                    if ok then Some { Degree = deg; Logs = logs } else None
            // '+' terms: the dominant one wins (max degree, then max logs)
            body.Split('+')
            |> Array.map (fun t -> t.Trim())
            |> Array.filter (fun t -> t.Length > 0)
            |> Array.map termShape
            |> fun shapes ->
                if shapes |> Array.exists Option.isNone then None
                else shapes |> Array.choose id |> Array.sortByDescending (fun s -> s.Degree, s.Logs) |> Array.tryHead

    /// Search the shelf by TIME budget: every (artifact, op) whose declared time degree ≤ d.
    /// (The function-selection constraint Aaron named: pick strategies by how long they take.)
    let searchTimeAtMost (d: int) : ((string * string) * Cost) list =
        declared
        |> Map.toList
        |> List.filter (fun (_, c) -> match parseO c.Time with Some s -> s.Degree <= d | None -> false)

    /// Search by SPACE budget — the memory axis, same discipline.
    let searchSpaceAtMost (d: int) : ((string * string) * Cost) list =
        declared
        |> Map.toList
        |> List.filter (fun (_, c) -> match parseO c.Space with Some s -> s.Degree <= d | None -> false)

    /// Rows whose O-strings the parser REFUSES — the search's honest blind spots (keep this
    /// visible: an unsearchable row is a row the budget-constrained picker cannot see).
    let unsearchable () : ((string * string) * string) list =
        declared
        |> Map.toList
        |> List.collect (fun (k, c) ->
            [ if (parseO c.Time).IsNone then yield k, c.Time
              if (parseO c.Space).IsNone then yield k, c.Space ])

    /// All declared ways to perform an operation FAMILY on an artifact — the "same shape,
    /// different O tradeoffs" query: a renderer (or a budget) picks a strategy BY its cost tag.
    let strategiesOf (artifact: string) : (string * Cost) list =
        declared
        |> Map.toList
        |> List.choose (fun ((a, op), cost) -> if a = artifact then Some(op, cost) else None)

    let unstated () : string list =
        let stated = declared |> Map.toList |> List.map (fst >> fst) |> Set.ofList
        let allNames =
            (GeneratorRegistry.known |> List.map (fun e -> e.Name))
            @ (LayoutEngine.known |> List.map (fun e -> e.Name))
            @ (IndexFormat.known |> List.map (fun f -> f.Entry.Name))
            @ (ControlScheme.known |> List.map (fun s -> s.Name))
            |> List.distinct
        allNames |> List.filter (fun n -> not (Set.contains n stated))

    /// ENTROPY HELD — the optional declaration: an artifact MAY hold entropy and says so (save state,
    /// identity). Absence = holds none (the zero case); presence = the holding is part of its surface.
    let entropyHeld: Map<string, string list> =
        Map.ofList
            [ "saves", [ "save-state recordings (the campaign notebook)" ]
              "rooms.persona", [ "identity (the persona's own; clause 2 — theirs)" ] ]

    /// THE BEN LINE (B-1039: the prediction lives WITH the room). A cartridge declares its own
    /// cost prediction in-file:
    ///
    ///     ben	draw	shape.dynamicvalue	O(children)
    ///
    /// (kind=ben, name=the operation, fields=[artifact; predicted time O]). benCheck cross-checks
    /// the in-file claim against THIS registry: an unparseable O, a row the registry does not
    /// carry, or a shape that disagrees with the registry's declared time all REFUSE — and the
    /// shelf sweep in ShapeAcceptance.Tests enforces it for every cartridge the moment it lands
    /// (same blade as THE GOLDEN LOCK: an in-file claim is checked in CI, never taken on faith).
    /// Runtime grading of the prediction (Confirmed/Tighter/Violated) stays Ben.grade's lane.
    type BenVerdict =
        { Op: string
          Artifact: string
          Ok: bool
          Evidence: string }

    let benCheck (d: MediaLines.Doc) : BenVerdict list =
        MediaLines.ofKind "ben" d
        |> List.map (fun e ->
            match e.Fields with
            | artifact :: predicted :: _ ->
                match parseO predicted with
                | None ->
                    { Op = e.Name
                      Artifact = artifact
                      Ok = false
                      Evidence = sprintf "unparseable prediction '%s' — refusal, never a guess" predicted }
                | Some shape ->
                    match Map.tryFind (artifact, e.Name) declared with
                    | None ->
                        { Op = e.Name
                          Artifact = artifact
                          Ok = false
                          Evidence = "no registry row — a prediction must point at a stated shelf cost (add the row or fix the name)" }
                    | Some cost ->
                        match parseO cost.Time with
                        | Some reg when reg = shape ->
                            { Op = e.Name
                              Artifact = artifact
                              Ok = true
                              Evidence = sprintf "prediction %s agrees with the registry's %s (degree %d, logs %d)" predicted cost.Time shape.Degree shape.Logs }
                        | Some _ ->
                            { Op = e.Name
                              Artifact = artifact
                              Ok = false
                              Evidence = sprintf "prediction %s DISAGREES with the registry's %s — one of them is lying; reconcile before the gate opens" predicted cost.Time }
                        | None ->
                            { Op = e.Name
                              Artifact = artifact
                              Ok = false
                              Evidence = sprintf "the registry's own '%s' is unsearchable — fix the registry row first" cost.Time }
            | _ ->
                { Op = e.Name
                  Artifact = "?"
                  Ok = false
                  Evidence = "a ben line must carry artifact and predicted O" })

    /// Does every in-file ben prediction agree with the registry? (No ben lines = vacuously true:
    /// the prediction is OPTIONAL in-file — the registry row is the required half; see unstated.)
    let benHolds (d: MediaLines.Doc) : bool = benCheck d |> List.forall (fun b -> b.Ok)

    /// THE BUDGET REFUSAL (B-1035 budget metering; Aaron: "constrain function selection by how
    /// long it takes — we have TIME too, not just memory"). A room states its budget as maximum
    /// polynomial degrees (time, space); asking for an over-budget strategy is REFUSED — and the
    /// refusal is USEFUL: it names every stated in-budget strategy on the same artifact, so the
    /// caller can re-plan instead of guessing. Unstated/unsearchable rows refuse too (a cost the
    /// shelf cannot price cannot be budgeted — honesty over convenience).
    let budgetCheck (artifact: string) (op: string) (maxTimeDegree: int) (maxSpaceDegree: int) : Result<Cost, string> =
        let inBudget (c: Cost) =
            match parseO c.Time, parseO c.Space with
            | Some t, Some s -> Some(t.Degree <= maxTimeDegree && s.Degree <= maxSpaceDegree)
            | _ -> None // unsearchable — cannot be budgeted
        match Map.tryFind (artifact, op) declared with
        | None ->
            Error(sprintf "BUDGET: (%s, %s) has no stated cost — the shelf requires stated costs before a budgeted room may call it" artifact op)
        | Some cost ->
            match inBudget cost with
            | None ->
                Error(sprintf "BUDGET: (%s, %s) declares unsearchable costs (%s / %s) — fix the registry row before budgeting" artifact op cost.Time cost.Space)
            | Some true -> Ok cost
            | Some false ->
                let alternatives =
                    strategiesOf artifact
                    |> List.filter (fun (o, c) -> o <> op && inBudget c = Some true)
                    |> List.map (fun (o, c) -> sprintf "%s (%s/%s)" o c.Time c.Space)
                let offer =
                    if List.isEmpty alternatives then "no stated in-budget strategy exists on this artifact"
                    else "in-budget strategies on the same artifact: " + String.concat ", " alternatives
                Error(sprintf "BUDGET REFUSED: (%s, %s) is %s time / %s space, over budget (time deg ≤ %d, space deg ≤ %d) — %s" artifact op cost.Time cost.Space maxTimeDegree maxSpaceDegree offer)
`;
}
function generateTS(entries) {
    let out = `// Auto-generated by src/Core.TypeScript/complexity/complexity-generator.ts. Do not edit.

export type Provenance = "Proven" | "Derived";

export interface Cost {
  time: string;
  space: string;
  by: Provenance;
}

export const DECLARED: Record<string, Cost> = {
`;
    entries.forEach((e) => {
        out += `  "${e.artifact}:${e.op}": { time: "${e.time}", space: "${e.space}", by: "${e.by}" },\n`;
    });
    out += `};\n`;
    return out;
}
function main() {
    const rootDir = path.resolve(__dirname, "../../..");
    const yamlPath = path.join(rootDir, "registry/complexity-registry.yaml");
    const entries = parseYamlFile(yamlPath);
    console.log(`Parsed ${entries.length} entries from ${yamlPath}`);
    // Write F#
    const fsPath = path.join(rootDir, "src/Core/ComplexityRegistry.fs");
    fs.writeFileSync(fsPath, generateFSharp(entries), "utf-8");
    console.log(`Wrote F# to ${fsPath}`);
    // Write TS
    const tsDir = path.join(rootDir, "src/Core.TypeScript/complexity");
    if (!fs.existsSync(tsDir)) {
        fs.mkdirSync(tsDir, { recursive: true });
    }
    const tsPath = path.join(tsDir, "complexity-registry.gen.ts");
    fs.writeFileSync(tsPath, generateTS(entries), "utf-8");
    console.log(`Wrote TS to ${tsPath}`);
    console.log("Running formatters...");
    try {
        execSync(`npx prettier --write "${tsPath}"`);
    }
    catch (err) {
        console.warn("Prettier failed:", err);
    }
    console.log("Complexity Registry Code Generation complete.");
}
main();
