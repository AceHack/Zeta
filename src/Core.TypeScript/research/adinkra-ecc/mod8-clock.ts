/** All `k`-subsets of `{0..n-1}`, as colour-index arrays. */
export function subsets(n: number, k: number): number[][] {
  const out: number[][] = [];
  const cur: number[] = [];
  const walk = (start: number): void => {
    if (cur.length === k) {
      out.push([...cur]);
      return;
    }
    for (let i = start; i < n; i++) {
      cur.push(i);
      walk(i + 1);
      cur.pop();
    }
  };
  walk(0);
  return out;
}

/** Does the code have a nonzero codeword supported inside the colour set? */
export function codeTouches(code: Mask[], subset: number[]): boolean {
  let mask = 0;
  for (const c of subset) mask |= 1 << c;
  return code.some((c) => c !== 0 && (c & ~mask) === 0);
}

export interface PeriodResult {
  /** `separates` at each `N`, index 0 unused so that `flags[N]` reads directly. */
  readonly flags: boolean[];
  /** The smallest `p >= 1` with `flags[N] === flags[N + p]` throughout the measured range. */
  readonly period: number;
  /** The `N` at which `separates` is true. */
  readonly separatingN: number[];
}

/**
 * Sweep the CODELESS tower and measure the period of `separates` directly, without ever asking
 * `N % 8`. The period is found by searching for the smallest shift under which the measured flag
 * sequence is invariant — so it can come out as anything, including "no period in range".
 */
export function separationPeriod(maxN: number, square: 1 | -1): PeriodResult {
  const flags: boolean[] = [false];
  for (let n = 1; n <= maxN; n++) {
    flags.push(clockByBlades((1 << n) - 1, square).separates);
  }
  let period = 0;
  for (let p = 1; p <= maxN; p++) {
    let ok = true;
    let compared = 0;
    for (let n = 1; n + p <= maxN; n++) {
      compared++;
      if (flags[n] !== flags[n + p]) {
        ok = false;
        break;
      }
    }
    // A shift with nothing to compare against is not evidence of a period.
    if (ok && compared >= p) {
      period = p;
      break;
    }
  }
  return {
    flags,
    period,
    separatingN: flags.map((f, n) => (f ? n : -1)).filter((n) => n > 0),
  };
}

/** Build the N = 8 self-dual adinkra used as the within-object experiment's single object. */
export function selfDualAdinkraN8(square: 1 | -1): CodedAdinkra {
  const codes = enumerateDoublyEvenCodes(8);
  const selfDual = codes.filter((g) => g.length === 4);
  const chosen = selfDual[0];
  if (chosen === undefined) throw new Error("no self-dual doubly-even code of length 8 found");
  return buildCodedAdinkra(8, chosen, square);
}

// ─────────────────────────────────────────────────────────────────────────────────────────────
// WHERE THE PERIOD-8 INVARIANT ACTUALLY LIVES
// ─────────────────────────────────────────────────────────────────────────────────────────────
//
// The separation clock above turns out to have period 4 on this family, not 8. The genuine
// period-8 Atiyah-Bott-Shapiro invariant is the MORITA GROUND — whether the simple module's
// endomorphism ring is R, C or H — and that is a different observable. `commutantDim` measures the
// quantity it is read from, and the measurement shows why the codeless tower cannot show it: for
// `k = 0` the vertex module IS the regular representation, whose endomorphism algebra is the whole
// algebra again (dimension 2^N), so the ground is hidden by construction. It becomes visible only
// once a code shrinks the module — which inverts the usual telling, in which the code only takes
// things away.

/**
 * `dim End_A(M)` — the dimension of the space of matrices commuting with every edge operator.
 *
 * Derivation of the recurrence, so the union-find below is not a magic trick. Writing the signed
 * permutation as `L_{to[j], j} = sign[j]`, the condition `L X = X L` reads
 *
 *     X[to[i]][to[j]] = sign[i] * sign[j] * X[i][j]
 *
 * — an orbit relation on index PAIRS carrying a sign. So the commutant's dimension is the number
 * of orbits on which the accumulated sign is consistent; an orbit that returns to itself with the
 * opposite sign forces its entries to zero and contributes nothing. Exact integer arithmetic, no
 * elimination, `O(|V|^2 * N)`.
 */
export function commutantDim(a: CodedAdinkra): number {
  const dim = a.reps.length;
  const total = dim * dim;
  const parent = new Int32Array(total);
  const parity = new Int8Array(total); // sign relative to the representative
  for (let i = 0; i < total; i++) {
    parent[i] = i;
    parity[i] = 1;
  }
  const find = (x: number): { root: number; sign: number } => {
    let r = x;
    let s = 1;
    while (parent[r] !== r) {
      s *= parity[r] ?? 1;
      r = parent[r] ?? r;
    }
    return { root: r, sign: s };
  };
  const inconsistent = new Set<number>();
  const union = (x: number, y: number, rel: number): void => {
    const fx = find(x);
    const fy = find(y);
    if (fx.root === fy.root) {
      if (fx.sign * fy.sign !== rel) inconsistent.add(fx.root);
      return;
    }
    parent[fy.root] = fx.root;
    parity[fy.root] = (rel * fx.sign * fy.sign) as number;
    if (inconsistent.delete(fy.root)) inconsistent.add(fx.root);
  };

  for (const op of a.L) {
    for (let i = 0; i < dim; i++) {
      for (let j = 0; j < dim; j++) {
        const ti = op.to[i] ?? 0;
        const tj = op.to[j] ?? 0;
        const rel = (op.sign[i] ?? 1) * (op.sign[j] ?? 1);
        union(i * dim + j, ti * dim + tj, rel);
      }
    }
  }
  const roots = new Set<number>();
  for (let i = 0; i < total; i++) roots.add(find(i).root);
  let free = 0;
  for (const r of roots) if (!inconsistent.has(r)) free++;
  return free;
}
