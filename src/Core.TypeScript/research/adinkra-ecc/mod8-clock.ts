// mod8-clock.ts — DOES THE CLOCK COME FROM THE CLIFFORD ALGEBRA OR FROM THE CODE?
//
// THE QUESTION. `src/Core/CliffordPeriodicity.fs:168` (`halvesSeparateCleanly`) carries the repo's
// only computed "mod-8 clock": the even subalgebra preserves the boson/fermion halves ("what
// remains"), the odd part swaps them ("what acts"), and the two halves separate into independent
// blocks exactly when the even part lands on a split row of the Atiyah-Bott-Shapiro table. That
// function is keyed on a SIGNATURE LITERAL `(p,q)` and never looks at an adinkra. Meanwhile
// `regular-representation-defect.ts` builds real edge operators for every doubly-even code and
// never asks the clock question of them. Nothing joins the two, which is the gap this file closes.
//
// The live dispute is about ORIGIN. Two candidates, and they make opposite predictions:
//
//   ORIGIN A — the code.  A doubly-even self-dual binary code exists only at length divisible by
//     8 (Gleason; Mallows-Sloane). If the clock comes from there, it must vanish where the code
//     does.
//   ORIGIN B — the Clifford algebra.  Real Clifford algebras repeat with period 8 in the
//     signature (Cartan; Bott 1959; Atiyah-Bott-Shapiro 1964, "Clifford Modules"; the tabular form
//     is Budinich-Trautman, *The Spinorial Chessboard*, 1988). If the clock comes from there, it
//     is indifferent to the code.
//
// THE EXPERIMENT, and why its design matters. Comparing the coded tower against the codeless tower
// varies two things at once — the code, and every other way two different constructions differ. So
// the measurement below is done WITHIN ONE OBJECT: one adinkra, one code, and the only thing that
// varies is whether the code's support meets the colour set being measured. At N = 8 with the
// self-dual [8,4,4] code there are C(8,4) = 70 four-colour subsets, of which 56 miss every codeword
// and 14 carry one (`regular-representation-defect.test.ts`, "free over Cl(0,T) exactly when no
// nonzero codeword is supported inside T"). Those 56 and those 14 are the treatment and control
// groups, and they are already known to DIFFER on a different observable — freeness — which is what
// makes the experiment non-blind: if the clock also differed, we would see it.
//
// WHAT "A MOD-8 CLOCK" MEANS HERE, pinned down before anything is measured, because an unpinned
// quantity cannot be falsified:
//
//     clock(T) = ( dim A_T, dim Z(A_T), omega^2, dim A_T^0, dim Z(A_T^0), omega0^2, separates )
//
// for A_T the algebra generated by the edge operators of the colours in T, A_T^0 its even part,
// Z the centre, omega the top product, and `separates` := Z(A_T^0) is 2-dimensional with its
// nontrivial element squaring to +1 (so the two central idempotents (1 +/- omega0)/2 are real and
// the even algebra is a direct sum of two ideals). `separates` is the operator-level form of
// `halvesSeparateCleanly`.
//
// TWO ROUTES, SHARING NO INTERMEDIATE — the discipline `mod-eight-correspondence.ts` set for
// itself ("a check that `e^{i pi n/4} === 1` exactly when 8 divides n would be a tautology"):
//
//   ROUTE M (matrix). Composes the adinkra's ACTUAL signed-permutation operators and decides
//     commutation by comparing matrices entry by entry. Never evaluates a sign formula.
//   ROUTE B (blade). Works on bitmasks with `cliffordSign` and decides commutation from the
//     reordering parity. Never builds a matrix, never knows there is an adinkra.
//
// Neither route contains `n % 8` anywhere. The period is READ OFF the resulting table, not
// asserted — which is the only way this can come out other than as expected.
//
// Anchors (each used for what it actually entails): Atiyah, Bott & Shapiro, *Clifford Modules*,
// Topology 3 (1964) — the mod-8 periodicity of real Clifford algebras, the load-bearing citation
// for ORIGIN B; Bott (1959) for the periodicity theorem the above specialises; Cartan for the
// original classification of real Clifford algebras; Gleason / Mallows-Sloane for ORIGIN A's
// length-divisible-by-8 theorem, which is included because without it the two origins would not
// be distinguishable and the experiment would have nothing to decide; Doran, Faux, Gates, Huebsch,
// Iga & Landweber, arXiv:0806.0051, for the adinkra/doubly-even-code correspondence the operators
// are built from.

